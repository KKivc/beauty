    'midNotWorseThan084', mid086 <= mid084 + tolerance, ...
    'fineReductionFrom084', fine084 - fine086, ...
    'midReductionFrom084', mid084 - mid086, ...
    'requiresVisualReview', true);
end

function value = safeRatio(numerator, denominator)
if denominator == 0
    value = NaN;
else
    value = numerator / denominator;
end
end

