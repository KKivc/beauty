function probes = makeFrequencyProbes(inputImage, inputYcbcr, frequency, ...
        smoothed, repaired)
originalY = double(frequency.base) + double(frequency.mid) + ...
    double(frequency.fine);
smoothingOnlyY = double(frequency.base) + double(smoothed.mid) + ...
    double(smoothed.fine);
smoothingPlusRepairY = double(frequency.base) + ...
    double(repaired.mid) + double(repaired.fine);
probes = struct( ...
    'original', [], ...
    'smoothingOnly', rebuildRgbWithOriginalChroma( ...
    smoothingOnlyY, inputYcbcr), ...
    'smoothingPlusRepair', rebuildRgbWithOriginalChroma( ...
    smoothingPlusRepairY, inputYcbcr), ...
    'originalLuminance', originalY, ...
    'smoothingOnlyLuminance', smoothingOnlyY, ...
    'smoothingPlusRepairLuminance', smoothingPlusRepairY, ...
    'smoothingOnlyLuminanceDelta', smoothingOnlyY - originalY, ...
    'repairLuminanceDelta', smoothingPlusRepairY - smoothingOnlyY, ...
    'baseStageApplied', false, ...
    'toneStageApplied', false, ...
    'whiteningStageApplied', false, ...
    'originalChromaPreserved', true);
% A 直接使用输入原图，不经过任何转换，作为真实视觉参考。
probes.original = inputImage;
end

function image = rebuildRgbWithOriginalChroma(luminance, inputYcbcr)
ycbcr = cat(3, min(max(double(luminance), 0), 1), ...
    inputYcbcr(:, :, 2), inputYcbcr(:, :, 3));
image = im2uint8(ycbcr2rgb(ycbcr));
end

function assessment = classifyCase(metrics, probes, options)
lash = metrics(strcmp({metrics.roi}, 'lashRoi'));
smoothingAction = lash.smoothingActionMeanAbs;
repairAction = lash.repairActionMeanAbs;
% 这里的阈值只用于“阶段作用量分诊”，不是视觉损伤分数。
meaningful = options.stageActionThreshold;
if smoothingAction < meaningful && repairAction < meaningful
    caseName = 'D';
    reason = 'Fine/Mid 两阶段在固定 lashRoi 内均未达到作用量分诊阈值。';
elseif smoothingAction >= meaningful && repairAction < meaningful
    caseName = 'A';
    reason = 'Smoothing 作用量达到阈值，Repair 作用量未达到阈值。';
elseif smoothingAction < meaningful && repairAction >= meaningful
    caseName = 'B';
    reason = 'Smoothing 作用量未达到阈值，Repair 作用量达到阈值。';
elseif repairAction <= .35 * smoothingAction
    caseName = 'A';
    reason = '两阶段均有作用，但 Repair 作用量不超过 Smoothing 的 35%。';
elseif smoothingAction <= .35 * repairAction
    caseName = 'B';
    reason = '两阶段均有作用，但 Smoothing 作用量不超过 Repair 的 35%。';
else
    caseName = 'C';
    reason = 'Smoothing 与 Repair 的作用量均达到阈值，且不存在明显单阶段主导。';
end
lashBounds = [lash.roiX, lash.roiY, lash.roiWidth, lash.roiHeight];
lashMask = makeRoiMask(lashBounds, ...
    [size(probes.original, 1), size(probes.original, 2)]);
assessment = struct( ...
    'case', caseName, ...
    'reason', reason, ...
    'classificationBasis', '固定 lashRoi 的 Fine/Mid 阶段作用量分诊；不是 RGB 损伤分数。', ...
    'smoothingActionMeanAbs', smoothingAction, ...
    'repairActionMeanAbs', repairAction, ...
    'stageActionThreshold', meaningful, ...
    'repairToSmoothingRatio', safeRatio(repairAction, smoothingAction), ...
    'smoothingProbeLuminanceChangeMean', mean(abs( ...
    probes.smoothingOnlyLuminanceDelta(lashMask))), ...
    'repairProbeLuminanceChangeMean', mean(abs( ...
    probes.repairLuminanceDelta(lashMask))));
end

