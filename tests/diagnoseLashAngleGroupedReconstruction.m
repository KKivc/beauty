    readDiagnosticArray(baselineTextureDiagnostics.occluderProtection, ...
    imageSize, 'occluderProtection'), ...
    readDiagnosticArray(baselineTextureDiagnostics.browProtection, ...
    imageSize, 'browProtection'), ...
    readDiagnosticArray(baselineTextureDiagnostics.lipProtection, ...
    imageSize, 'lipProtection'), ...
    readDiagnosticArray(baselineTextureDiagnostics.noseProtection, ...
    imageSize, 'noseProtection')), [], 3);
candidate086TextureProtectionMask = min(max(max(fixedTextureComponents, ...
    candidate086EyeDetailProtection), 0), 1);
candidate087TextureProtectionMask = min(max(max(fixedTextureComponents, ...
    candidate087EyeDetailProtection), 0), 1);
validateMask(candidate086TextureProtectionMask, imageSize, ...
    'candidate086TextureProtectionMask');
validateMask(candidate087TextureProtectionMask, imageSize, ...
    'candidate087TextureProtectionMask');

