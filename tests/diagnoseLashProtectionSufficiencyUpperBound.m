        'outputCb', composeDiagnostics.toneTargetCb, ...
        'outputCr', composeDiagnostics.toneTargetCr), ...
    'whitening', struct('supportMap', composeDiagnostics.whiteningSupport, ...
        'delta', composeDiagnostics.whiteningDelta));
end

