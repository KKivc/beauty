function evidence = reconstructExistingLashEvidence(inputImage, context, ...
        faceScale)
imageSize = [size(inputImage, 1), size(inputImage, 2)];
if ~isfield(context, 'regions') || ~isfield(context, 'regionConfidence')
    error('diagnoseLashAngleGroupedReconstruction:MissingSemanticEvidence', ...
        '固定 Context 缺少当前 detector 所需的 regions/regionConfidence。');
end
regions = context.regions;
confidence = context.regionConfidence;
required = {'leftEye', 'rightEye', 'leftBrow', 'rightBrow'};
if ~all(isfield(regions, required)) || ~all(isfield(confidence, required))
    error('diagnoseLashAngleGroupedReconstruction:MissingSemanticEvidence', ...
        '固定 Context 缺少眼睛或眉毛既有语义 evidence。');
end
leftEyeEvidence = min(double(regions.leftEye), ...
    double(confidence.leftEye));
rightEyeEvidence = min(double(regions.rightEye), ...
    double(confidence.rightEye));
browEvidence = max(min(double(regions.leftBrow), ...
    double(confidence.leftBrow)), min(double(regions.rightBrow), ...
    double(confidence.rightBrow)));
validateArray(leftEyeEvidence, imageSize, 'leftEyeEvidence');
validateArray(rightEyeEvidence, imageSize, 'rightEyeEvidence');
validateArray(browEvidence, imageSize, 'browEvidence');

grayImage = im2double(rgb2gray(inputImage));
identityThreshold = .45;
softSupportThreshold = .20;
identityMasks = {leftEyeEvidence >= identityThreshold, ...
    rightEyeEvidence >= identityThreshold};
softSupportMasks = {leftEyeEvidence >= softSupportThreshold & ...
    leftEyeEvidence < identityThreshold, ...
    rightEyeEvidence >= softSupportThreshold & ...
    rightEyeEvidence < identityThreshold};
browCore = browEvidence >= identityThreshold;
periocularRadius = min(24, max(9, round(.040 * double(faceScale))));
softRadius = min(5, max(2, round(.008 * double(faceScale))));

angles = 0:15:165;
angleCount = numel(angles);
allNeighborhood = false(imageSize);
allRing = false(imageSize);
allDarkCandidate = false(imageSize);
allEdgeCandidate = false(imageSize);
allLineSupport = false(imageSize);
allAngleResponse = cell(1, angleCount);
for angleIndex = 1:angleCount
    allAngleResponse{angleIndex} = false(imageSize);
end
allDetectorCandidate = false(imageSize);
allLashCore = false(imageSize);
allLashProtection = zeros(imageSize);
allLaunchMask = false(imageSize);
allNearEye = false(imageSize);
perEye = cell(1, numel(identityMasks));
for eyeIndex = 1:numel(identityMasks)
    identityCore = identityMasks{eyeIndex};
    softSupport = softSupportMasks{eyeIndex};
    launchMask = identityCore | softSupport;
    if ~any(launchMask(:))
        continue;
    end
    currentBand = imdilate(launchMask, ...
        strel('disk', periocularRadius, 0));
    currentRing = currentBand & ~launchMask;
    if any(browCore(:))
        browRadius = min(5, max(2, round(.010 * double(faceScale))));
        browExclusion = imdilate(browCore, strel('disk', browRadius, 0));
        currentRing(browExclusion) = false;
    end
    current = reconstructExistingLashLines(grayImage, launchMask, ...
        currentRing, identityCore, faceScale, softRadius, ...
        any(softSupport(:)));
    allNeighborhood = allNeighborhood | currentBand;
    allRing = allRing | currentRing;
    allDarkCandidate = allDarkCandidate | current.darkCandidate;
    allEdgeCandidate = allEdgeCandidate | current.edgeCandidate;
    allLineSupport = allLineSupport | current.lineSupport;
    for angleIndex = 1:angleCount
        allAngleResponse{angleIndex} = allAngleResponse{angleIndex} | ...
            current.lineResponse{angleIndex};
    end
    allDetectorCandidate = allDetectorCandidate | current.candidate;
    allLashCore = allLashCore | current.lashCore;
    allLashProtection = max(allLashProtection, current.protection);
    allLaunchMask = allLaunchMask | launchMask;
    allNearEye = allNearEye | current.nearEye;
    perEye{eyeIndex} = current;
end

lineSupportFromAngleResponse = false(imageSize);
for angleIndex = 1:angleCount
    lineSupportFromAngleResponse = lineSupportFromAngleResponse | ...
        allAngleResponse{angleIndex};
end
lineSupportFromAngleMaxError = max(abs(double(lineSupportFromAngleResponse(:)) - ...
    double(allLineSupport(:))));
if lineSupportFromAngleMaxError > 0
    error('diagnoseLashAngleGroupedReconstruction:AngleResponseUnionMismatch', ...
        '逐 angle response union 与当前 lineSupport 不一致。');
end

% 当前 detector 的 evidence 只在现有眼周 ring 和既有 near-eye 约束内
% 允许参与几何重构。edgeCandidate 是 darkCandidate 的既有子集，仍显式
% 保留三类 evidence 名称以便离线诊断和审计。
allowedEvidence = allRing & allNearEye & ...
    (allDarkCandidate | allEdgeCandidate | allLineSupport);
seed = allDetectorCandidate & allowedEvidence;
if any(seed(:))
    connectedEvidence = imreconstruct(seed, allowedEvidence, 8);
else
    connectedEvidence = false(imageSize);
end

evidence = struct( ...
    'angles', angles, ...
    'faceScale', double(faceScale), ...
    'periocularRadius', periocularRadius, ...
    'softRadius', softRadius, ...
    'softPeak', .99, ...
    'leftEyeEvidence', leftEyeEvidence, ...
    'rightEyeEvidence', rightEyeEvidence, ...
    'browEvidence', browEvidence, ...
    'browCore', browCore, ...
    'eyeNeighborhood', allNeighborhood, ...
    'ring', allRing, ...
    'launchMask', allLaunchMask, ...
    'nearEye', allNearEye, ...
    'darkCandidate', allDarkCandidate, ...
    'edgeCandidate', allEdgeCandidate, ...
    'lineSupport', allLineSupport, ...
    'lineResponse', {allAngleResponse}, ...
    'lineSupportFromAngleResponse', lineSupportFromAngleResponse, ...
    'lineSupportFromAngleMaxError', lineSupportFromAngleMaxError, ...
    'detectorSeed', allDetectorCandidate, ...
    'lashCore', allLashCore, ...
    'existingLashProtection', allLashProtection, ...
    'allowedEvidence', allowedEvidence, ...
    'connectedEvidence', connectedEvidence, ...
    'perEye', {perEye});
end

function result = reconstructExistingLashLines(grayImage, launchMask, ...
        ring, identityCore, faceScale, softRadius, allowSoftProtection)
% 下列尺度、百分位和逻辑逐字复用当前生产 detectLashLines。它们不是
% 08.7 候选参数；该复制用于在不修改 src 的离线票中重建内部 evidence，
% 并由 baseline lashProtection 精确一致性检查防止诊断漂移。
result = struct();
angles = 0:15:165;
result.angles = angles;
result.lineResponse = cell(1, numel(angles));
for angleIndex = 1:numel(angles)
    result.lineResponse{angleIndex} = false(size(launchMask));
end
result.lashCore = false(size(launchMask));
result.protection = zeros(size(launchMask));
result.darkCandidate = false(size(launchMask));
result.edgeCandidate = false(size(launchMask));
result.lineSupport = false(size(launchMask));
result.candidate = false(size(launchMask));
result.nearEye = false(size(launchMask));
if ~any(ring(:))
    return;
end

darkSigma = min(2.4, max(.7, .004 * double(faceScale)));
lineSigma = min(1.35, max(.45, .002 * double(faceScale)));
smoothed = imgaussfilt(grayImage, darkSigma, 'Padding', 'replicate');
lineImage = imgaussfilt(grayImage, lineSigma, 'Padding', 'replicate');
[gradientX, gradientY] = gradient(lineImage);
gradientMagnitude = hypot(gradientX, gradientY);
darkResidual = smoothed - grayImage;
darkValues = sort(darkResidual(ring));
gradientValues = sort(gradientMagnitude(ring));
darkThreshold = max(.010, percentileValue(darkValues, .62));
gradientThreshold = max(.012, percentileValue(gradientValues, .65));
darkCandidate = ring & darkResidual >= darkThreshold;
edgeCandidate = darkCandidate & gradientMagnitude >= gradientThreshold;
if ~any(darkCandidate(:))
    return;
end
lineLength = min(6, max(3, round(.007 * double(faceScale))));
gapLength = min(5, max(2, round(.006 * double(faceScale))));
lineSupport = false(size(darkCandidate));
for angleIndex = 1:numel(angles)
    angle = angles(angleIndex);
    closingElement = strel('line', gapLength, angle);
    openingElement = strel('line', lineLength, angle);
    closed = imclose(darkCandidate, closingElement);
    currentResponse = imdilate(imopen(closed, openingElement), ...
        strel('disk', 1, 0));
    result.lineResponse{angleIndex} = currentResponse;
    lineSupport = lineSupport | currentResponse;
end
candidate = darkCandidate & (edgeCandidate | lineSupport);
lashDistance = min(9, max(4, round(.014 * double(faceScale))));
nearEye = bwdist(launchMask) <= lashDistance;
candidate = candidate & nearEye;
hardDarkThreshold = max(.045, percentileValue(darkValues, .80));
hardGradientThreshold = max(.018, percentileValue(gradientValues, .75));
if any(identityCore(:))
    hardNearEye = bwdist(identityCore) <= lashDistance;
    result.lashCore = candidate & ~identityCore & hardNearEye & ...
        darkResidual >= hardDarkThreshold & ...
        (gradientMagnitude >= hardGradientThreshold | lineSupport);
end
if allowSoftProtection
    protectionSeed = candidate;
else
    protectionSeed = result.lashCore;
end
if any(protectionSeed(:))
    result.protection = featherSoftMask(protectionSeed, softRadius, .99);
    result.protection(protectionSeed) = .99;
end
result.darkCandidate = darkCandidate;
result.edgeCandidate = edgeCandidate;
result.lineSupport = lineSupport;
result.candidate = candidate;
result.nearEye = nearEye;
end

function grouped = reconstructAngleGroupedGeometry(evidence)
angles = evidence.angles;
angleCount = numel(angles);
angleResponse = evidence.lineResponse;
allowedEvidence = cell(1, angleCount);
seed = cell(1, angleCount);
reconstructed = cell(1, angleCount);
unionGeometry = false(size(evidence.eyeNeighborhood));
for angleIndex = 1:angleCount
    response = logical(angleResponse{angleIndex});
    % 08.7 只复用已有 detector evidence。与 08.6 相比，
    % lineResponse_k 在 reconstruction 前不再与其它 angle OR。
    currentAllowed = evidence.ring & evidence.nearEye & ...
        evidence.darkCandidate & ...
        (evidence.edgeCandidate | response) & response;
    currentSeed = evidence.detectorSeed & currentAllowed;
    if any(currentSeed(:))
        currentReconstruction = imreconstruct(currentSeed, ...
            currentAllowed, 8);
    else
        currentReconstruction = false(size(currentSeed));
    end
    if any(currentReconstruction(:) & ~currentAllowed(:))
        error('diagnoseLashAngleGroupedReconstruction:AngleReconstructionEscape', ...
            'angle %g reconstruction 超出自身 allowedEvidence。', ...
            angles(angleIndex));
    end
    allowedEvidence{angleIndex} = currentAllowed;
    seed{angleIndex} = currentSeed;
    reconstructed{angleIndex} = currentReconstruction;
    unionGeometry = unionGeometry | currentReconstruction;
end

overlapMatrix = zeros(angleCount, angleCount);
for row = 1:angleCount
    for column = row:angleCount
        overlapMatrix(row, column) = nnz(reconstructed{row} & ...
            reconstructed{column});
        overlapMatrix(column, row) = overlapMatrix(row, column);
    end
end
pairwiseOverlapPixels = sum(overlapMatrix(triu(true(angleCount), 1)));
angleOverlapMask = false(size(unionGeometry));
for angleIndex = 1:angleCount
    other = false(size(unionGeometry));
    for otherIndex = 1:angleCount
        if otherIndex ~= angleIndex
            other = other | reconstructed{otherIndex};
        end
    end
    angleOverlapMask = angleOverlapMask | ...
        (reconstructed{angleIndex} & other);
end
angleStats = struct( ...
    'angles', angles, ...
    'responsePixels', zeros(1, angleCount), ...
    'seedPixels', zeros(1, angleCount), ...
    'reconstructedPixels', zeros(1, angleCount), ...
    'overlapPixels', zeros(1, angleCount));
for angleIndex = 1:angleCount
    angleStats.responsePixels(angleIndex) = nnz(angleResponse{angleIndex});
    angleStats.seedPixels(angleIndex) = nnz(seed{angleIndex});
    angleStats.reconstructedPixels(angleIndex) = nnz(reconstructed{angleIndex});
    angleStats.overlapPixels(angleIndex) = nnz(angleOverlapMask & ...
        reconstructed{angleIndex});
end
angleStats.pairwiseOverlapPixels = pairwiseOverlapPixels;
angleStats.finalUnionPixels = nnz(unionGeometry);
angleStats.finalOverlapPixels = nnz(angleOverlapMask);

grouped = struct( ...
    'angles', angles, ...
    'response', {angleResponse}, ...
    'allowedEvidence', {allowedEvidence}, ...
    'seed', {seed}, ...
    'reconstructed', {reconstructed}, ...
    'unionGeometry', unionGeometry, ...
    'overlapMatrix', overlapMatrix, ...
    'overlapMask', angleOverlapMask, ...
    'angleStats', angleStats);
end

function validateEvidenceReconstruction(evidence, textureDiagnostics, ...
        baselineLashProtection, imageSize, tolerance)
expectedNeighborhood = logical(textureDiagnostics.eyeNeighborhood);
expectedCore = logical(textureDiagnostics.lashCore);
if ~isequal(evidence.eyeNeighborhood, expectedNeighborhood)
    error('diagnoseLashAngleGroupedReconstruction:EvidenceNeighborhoodMismatch', ...
        '重建的 eyeNeighborhood 与当前生产 evidence 不一致。');
end
if ~isequal(evidence.lashCore, expectedCore)
    error('diagnoseLashAngleGroupedReconstruction:EvidenceCoreMismatch', ...
        '重建的 lashCore 与当前生产 evidence 不一致。');
end
maxError = max(abs(evidence.existingLashProtection(:) - ...
    baselineLashProtection(:)));
if maxError > tolerance
    error('diagnoseLashAngleGroupedReconstruction:EvidenceProtectionMismatch', ...
        '重建的现有 lashProtection 最大误差 %.17g。', maxError);
end
evidence.reconstructionMaxError = maxError;
if evidence.lineSupportFromAngleMaxError > tolerance
    error('diagnoseLashAngleGroupedReconstruction:AngleResponseUnionMismatch', ...
        'angle response union 最大误差 %.17g。', ...
        evidence.lineSupportFromAngleMaxError);
end
if numel(evidence.lineResponse) ~= numel(evidence.angles)
    error('diagnoseLashAngleGroupedReconstruction:MissingAngleResponse', ...
        'angle response 数量与固定 angle 集合不一致。');
end
for angleIndex = 1:numel(evidence.angles)
    validateMask(evidence.lineResponse{angleIndex}, imageSize, ...
        sprintf('lineResponse{%d}', angleIndex));
end
if any(evidence.connectedEvidence(:) & ~evidence.allowedEvidence(:))
    error('diagnoseLashAngleGroupedReconstruction:InvalidConnectedEvidence', ...
        'connectedEvidence 超出 allowedEvidence。');
end
if any(evidence.connectedEvidence(:) & ~evidence.eyeNeighborhood(:))
    error('diagnoseLashAngleGroupedReconstruction:InvalidNeighborhood', ...
        'connectedEvidence 超出 eyeNeighborhood。');
end
validateArray(evidence.existingLashProtection, imageSize, ...
    'existingLashProtection');
end

