function [energyBefore, energyAfter, ratio, status] = energyRetention( ...
        inputBand, outputBand, mask)
energyBefore = meanOn(abs(inputBand), mask);
energyAfter = meanOn(abs(outputBand), mask);
if isempty(inputBand(mask))
    ratio = NaN;
    status = '空选区';
elseif energyBefore <= eps
    ratio = NaN;
    status = '输入能量为零';
else
    ratio = energyAfter / energyBefore;
    status = '可用';
end
end

function [featureMasks, definitions] = buildFeatureMasks(context, safetyMasks)
imageSize = size(safetyMasks.hair);
regions = readSemanticStruct(context, 'regions', imageSize);
confidence = readSemanticStruct(context, 'regionConfidence', imageSize);
