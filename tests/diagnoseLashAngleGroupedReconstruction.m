end
stats = struct( ...
    'values', values, ...
    'count', numel(values), ...
    'sum', sum(values), ...
    'mean', mean(values), ...
    'min', min(values), ...
    'max', max(values), ...
    'nonzeroPixels', nnz(abs(values) > tolerance), ...
    'nonzeroFraction', nnz(abs(values) > tolerance) / numel(values));
