function assessment = assessNumericEvidence(metrics, supportChangedPixels, tolerance)
finiteValues = [ ...
    metrics.candidateLashProtection.mean, ...
    metrics.upperBoundLashProtection.mean, ...
    metrics.baselineRepairFineAbsAction.sum, ...
    metrics.candidateRepairFineAbsAction.sum, ...
    metrics.upperBoundRepairFineAbsAction.sum, ...
    metrics.baselineRepairMidAbsAction.sum, ...
    metrics.candidateRepairMidAbsAction.sum, ...
    metrics.upperBoundRepairMidAbsAction.sum, ...
    metrics.baselineFinalRgbDistanceToOriginal.mean, ...
    metrics.candidateFinalRgbDistanceToOriginal.mean, ...
    metrics.upperBoundFinalRgbDistanceToOriginal.mean, ...
    metrics.baselineFinalLuminanceDistanceToOriginal.mean, ...
    metrics.candidateFinalLuminanceDistanceToOriginal.mean, ...
    metrics.upperBoundFinalLuminanceDistanceToOriginal.mean];
finiteEvidence = all(isfinite(finiteValues));
hardUnchanged = all(struct2array(metrics.hardProtectionMaskChangedPixels) == 0) && ...
    all(struct2array(metrics.lashCoreChangedPixels) == 0) && ...
    all(struct2array(metrics.hardProtectedFinalRgbChangedCount) == 0);
strengthRaised = metrics.upperBoundLashProtection.mean >= ...
    metrics.candidateLashProtection.mean - tolerance && ...
    metrics.upperBoundLashStrengthRaisedPixels > 0;
fineReduced = metrics.repairFineUpperBoundReduction > tolerance;
midReduced = metrics.repairMidUpperBoundReduction > tolerance;
rgbCloser = metrics.finalRgbUpperBoundDistanceReduction > tolerance;
lumaCloser = metrics.finalLuminanceUpperBoundDistanceReduction > tolerance;
if finiteEvidence && supportChangedPixels == 0 && strengthRaised && ...
        hardUnchanged
    caseName = 'numericUpperBoundConstructed';
else
    caseName = 'numericUpperBoundConstructionFailed';
end
assessment = struct( ...
    'case', caseName, ...
    'requiresVisualReview', true, ...
    'supportUnchanged', supportChangedPixels == 0, ...
    'strengthRaised', strengthRaised, ...
    'fineAbsActionReduced', fineReduced, ...
    'midAbsActionReduced', midReduced, ...
    'finalRgbCloserToOriginal', rgbCloser, ...
    'finalLuminanceCloserToOriginal', lumaCloser, ...
    'hardAndCoreUnchanged', hardUnchanged, ...
    'finiteEvidence', finiteEvidence, ...
    'basis', ['数值部分只核对同一 Candidate support 内的强度上限、', ...
        '同次 Smoothing/Repair/compose 和硬保护不变；Case A/B/C 必须结合四列主图人工判定。']);
end

function stats = makeStats(values, tolerance)
values = double(values(:));
if isempty(values)
    stats = struct('values', values, 'count', 0, 'sum', 0, ...
        'mean', NaN, 'min', NaN, 'max', NaN, ...
        'nonzeroPixels', 0, 'nonzeroFraction', NaN);
    return;
end
stats = struct( ...
    'values', values, ...
    'count', numel(values), ...
    'sum', sum(values), ...
    'mean', mean(values), ...
    'min', min(values), ...
    'max', max(values), ...
    'nonzeroPixels', nnz(abs(values) > tolerance), ...
    'nonzeroFraction', nnz(abs(values) > tolerance) / numel(values));
end

