smoothed.retentionMap = fineRetentionMap;
smoothed.actualFineRetentionMap = fineRetentionMap;
smoothed.fineActualRetentionMap = fineRetentionMap;
smoothed.midAlphaMap = midAlphaMap;
smoothed.midRetention = midRetention;
smoothed.mediumRetention = midRetention;
smoothed.midRetentionMap = midRetentionMap;
smoothed.mediumRetentionMap = midRetentionMap;
smoothed.actualMidRetentionMap = midRetentionMap;
smoothed.midActualRetentionMap = midRetentionMap;
smoothed.actualMediumRetentionMap = midRetentionMap;
diagnostics = struct( ...
    'alphaMap', alphaMap, ...
    'fineAlphaMap', alphaMap, ...
    'midAlphaMap', midAlphaMap, ...
    'profile', profile, ...
    'fineRetention', fineRetention, ...
    'effectiveProfileFineRetention', fineRetention, ...
    'profileFineRetention', baselineSmoothing.profileFineRetention, ...
    'profileMediumRetention', baselineSmoothing.profileMediumRetention, ...
    'adaptiveFineRetention', fineRetention, ...
    'noseMidGate', noseMidGate, ...
    'midStructureGate', midStructureGate, ...
    'fineStructureGate', fineStructureGate, ...
    'fineProtectionMask', fineProtection, ...
    'fineRetentionMap', fineRetentionMap, ...
    'retentionMap', fineRetentionMap, ...
    'midRetention', midRetention, ...
    'mediumRetention', midRetention, ...
    'midRetentionMap', midRetentionMap, ...
    'mediumRetentionMap', midRetentionMap, ...
    'fineActualRetentionMap', fineRetentionMap, ...
    'actualFineRetentionMap', fineRetentionMap, ...
    'midActualRetentionMap', midRetentionMap, ...
    'actualMidRetentionMap', midRetentionMap, ...
    'actualMediumRetentionMap', midRetentionMap, ...
    'protectionMask', max(cat(3, textureProtection, ...
    structureProtection, hardProtection), [], 3), ...
    'fineBefore', double(frequency.fine), ...
    'fineAfter', smoothedFine, ...
    'midBefore', double(frequency.mid), ...
    'midAfter', smoothedMid, ...
    'fineEnergyBefore', mean(abs(double(frequency.fine(:)))), ...
    'fineEnergyAfter', mean(abs(smoothedFine(:))), ...
    'midEnergyBefore', mean(abs(double(frequency.mid(:)))), ...
    'midEnergyAfter', mean(abs(smoothedMid(:))), ...
    'fineActualRetention', mean(fineRetentionMap(:)), ...
    'midActualRetention', mean(midRetentionMap(:)), ...
