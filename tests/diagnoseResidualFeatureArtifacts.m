function [summary, diagnostics] = diagnoseResidualFeatureArtifacts( ...
        imagePath, outputFolder, options)
%DIAGNOSERESIDUALFEATUREARTIFACTS 诊断耳部、鼻孔及眉眼残留失真。
%   入口只接受人工指定的固定选区，记录语义证据、软硬保护、各处理
%   阶段的实际作用量，并在本诊断入口内执行单因素对照。所有消融和
%   局部保护注入都不写回生产 Context、Mask 或算法参数。

projectRoot = fileparts(fileparts(mfilename('fullpath')));
if nargin < 3
    options = [];
end
options = normalizeOptions(options);
productionRoot = resolveProductionRoot(projectRoot, options);
addpath(fullfile(productionRoot, 'src'), '-begin');
contract = beautyPipelineContract();
validateProductionContract(contract);
if nargin < 1 || isempty(imagePath)
    error('diagnoseResidualFeatureArtifacts:MissingImagePath', ...
        '必须提供输入图像路径。');
end
inputImage = readInputImage(imagePath);
if isfield(options, 'faceBox') && ~isempty(options.faceBox)
    validateRoiBounds(options.faceBox, size(inputImage), 'faceBox');
end
roiDefinitions = makeRegionDefinitions(options);
for index = 1:numel(roiDefinitions)
    roiDefinitions(index).roi = validateRoiBounds( ...
        roiDefinitions(index).roi, size(inputImage), ...
        roiDefinitions(index).name);
end

if nargin < 2 || isempty(outputFolder)
    outputFolder = fullfile(tempdir, ...
        'image_beauty_residual_feature_diagnosis');
end
if ~ischar(outputFolder) && ...
        ~(isstring(outputFolder) && isscalar(outputFolder))
    error('diagnoseResidualFeatureArtifacts:InvalidOutputFolder', ...
        '输出目录必须是文本路径。');
end
outputFolder = char(outputFolder);
if ~isfolder(outputFolder)
    mkdir(outputFolder);
end

if isfield(options, 'precomputedDiagnosticsPath') && ...
        ~isempty(options.precomputedDiagnosticsPath)
    [modes, previewScale, previewFaceBox, fullFaceBox, detection] = ...
        makePrecomputedModes(inputImage, options, roiDefinitions);
else
    [previewImage, previewScale] = makePreview(inputImage);
    [previewFaceBox, hasFace, detection] = detectSingleFace(previewImage);
    if ~hasFace
        error('diagnoseResidualFeatureArtifacts:NoFace', ...
            '输入图像未检测到可用的语义人脸。');
    end
    if isfield(options, 'faceBox') && ~isempty(options.faceBox)
        expectedPreviewFaceBox = scaleFaceBox(options.faceBox, previewScale, ...
            size(previewImage));
        if ~isequal(double(previewFaceBox), double(expectedPreviewFaceBox))
            error('diagnoseResidualFeatureArtifacts:FaceBoxMismatch', ...
                '检测到的人脸框与固定诊断人脸框不一致。');
        end
    end
    previewContext = prepareBeautyContext(previewImage, previewFaceBox, ...
        detection.selectedParsing, struct('rotationDegrees', ...
        detection.orientationDegrees));
    fullFaceBox = scaleFaceBox(previewFaceBox, 1 / previewScale, ...
        size(inputImage));
    if previewScale < 1
        fullContext = resizeBeautyContext(previewContext, size(inputImage), ...
            fullFaceBox, inputImage);
    else
        fullContext = previewContext;
    end

    if previewScale < 1
        modes = { ...
            struct('name', 'preview', 'image', previewImage, ...
            'faceBox', previewFaceBox, 'context', previewContext, ...
            'scale', previewScale), ...
            struct('name', 'original', 'image', inputImage, ...
            'faceBox', fullFaceBox, 'context', fullContext, 'scale', 1)};
    else
        modes = {struct('name', 'original', 'image', inputImage, ...
            'faceBox', fullFaceBox, 'context', fullContext, 'scale', 1)};
    end
end

regionRows = repmat(emptyRegionRow(), 0, 1);
ablationRows = repmat(emptyAblationRow(), 0, 1);
repairComponentRows = repmat(emptyRepairComponentRow(), 0, 1);
repairCombinationRows = repmat(emptyRepairCombinationRow(), 0, 1);
imageMetricRows = repmat(emptyImageMetricRow(), 0, 1);
modeDiagnostics = cell(1, numel(modes));
for modeIndex = 1:numel(modes)
    mode = modes{modeIndex};
    modeDefinitions = scaleDefinitions(roiDefinitions, mode.scale, ...
        size(mode.image));
    [modeResult, currentRegionRows, currentAblationRows, ...
        currentRepairComponentRows, currentRepairCombinationRows] = ...
        diagnoseMode(mode, modeDefinitions, options);
    modeDiagnostics{modeIndex} = modeResult;
    regionRows = [regionRows; currentRegionRows]; %#ok<AGROW>
    ablationRows = [ablationRows; currentAblationRows]; %#ok<AGROW>
    repairComponentRows = [repairComponentRows; ...
        currentRepairComponentRows]; %#ok<AGROW>
    repairCombinationRows = [repairCombinationRows; ...
        currentRepairCombinationRows]; %#ok<AGROW>
    imageMetricRows(end + 1, 1) = makeImageMetricRow( ...
        mode.name, modeResult.imageMetrics); %#ok<AGROW>
end

regionMetrics = struct2table(regionRows);
ablationMetrics = struct2table(ablationRows);
repairComponentMetrics = struct2table(repairComponentRows);
repairCombinationMetrics = struct2table(repairCombinationRows);
imageMetrics = struct2table(imageMetricRows);
paths = writeArtifacts(outputFolder, modeDiagnostics, regionMetrics, ...
    ablationMetrics, repairComponentMetrics, repairCombinationMetrics, ...
    imageMetrics);
summary = struct( ...
    'completed', true, ...
    'contract', contract, ...
    'imagePath', char(imagePath), ...
    'inputSize', size(inputImage), ...
    'previewScale', previewScale, ...
    'previewFaceBox', previewFaceBox, ...
    'originalFaceBox', fullFaceBox, ...
    'orientationDegrees', detection.orientationDegrees, ...
    'parameters', struct( ...
    'smoothingStrength', options.smoothingStrength, ...
    'whiteningStrength', options.whiteningStrength), ...
    'rois', roiDefinitions, ...
    'regionMetrics', regionMetrics, ...
    'ablationMetrics', ablationMetrics, ...
    'repairComponentMetrics', repairComponentMetrics, ...
    'repairCombinationMetrics', repairCombinationMetrics, ...
    'imageMetrics', imageMetrics, ...
    'paths', paths);
compactModes = compactModeDiagnostics(modeDiagnostics);
diagnostics = struct( ...
    'contract', contract, ...
    'detection', compactDetection(detection), ...
    'modes', {compactModes}, ...
    'paths', paths);
dataPath = fullfile(outputFolder, ...
    'residualFeatureDiagnosticData.mat');
summary.paths.data = dataPath;
diagnostics.paths.data = dataPath;
clear modeDiagnostics compactModes;
save(dataPath, 'summary', 'diagnostics', '-v7.3');
end

function root = resolveProductionRoot(projectRoot, options)
root = projectRoot;
if isfield(options, 'productionRoot') && ~isempty(options.productionRoot)
    if ~ischar(options.productionRoot) && ...
            ~(isstring(options.productionRoot) && ...
            isscalar(options.productionRoot))
        error('diagnoseResidualFeatureArtifacts:InvalidProductionRoot', ...
            '生产算法根目录必须是文本路径。');
    end
    root = char(options.productionRoot);
end
if ~isfolder(root) || ~isfolder(fullfile(root, 'src'))
    error('diagnoseResidualFeatureArtifacts:InvalidProductionRoot', ...
        '生产算法根目录或 src 目录不存在：%s。', root);
end
end

function validateProductionContract(contract)
required = {'schemaVersion', 'algorithmVersion', 'artifactVersion'};
if ~isstruct(contract) || ~isscalar(contract) || ...
        ~all(isfield(contract, required)) || ...
        ~strcmp(char(contract.schemaVersion), '4.0') || ...
        ~strcmp(char(contract.algorithmVersion), 'v3.3') || ...
        ~strcmp(char(contract.artifactVersion), 'v3.2')
    error('diagnoseResidualFeatureArtifacts:InvalidProductionBaseline', ...
        '生产依赖必须是已验证的 v3.3、Schema 4.0、产物 v3.2 基线。');
end
end

function [modes, previewScale, previewFaceBox, fullFaceBox, detection] = ...
        makePrecomputedModes(inputImage, options, definitions)
requiredOptions = {'faceBox', 'existingRegionMetricsPath', ...
    'existingImageMetricsPath'};
for index = 1:numel(requiredOptions)
    name = requiredOptions{index};
    if ~isfield(options, name) || isempty(options.(name))
        error('diagnoseResidualFeatureArtifacts:MissingPrecomputedArtifact', ...
            '复用已有基线时必须提供 %s。', name);
    end
end
diagnosticPath = requireFileOption(options, 'precomputedDiagnosticsPath');
regionPath = requireFileOption(options, 'existingRegionMetricsPath');
imageMetricPath = requireFileOption(options, 'existingImageMetricsPath');
loaded = load(diagnosticPath, 'diagnostics', 'context', 'output');
if ~isfield(loaded, 'diagnostics')
    error('diagnoseResidualFeatureArtifacts:InvalidPrecomputedArtifact', ...
        '已有基线 MAT 缺少 diagnostics 结构：%s。', diagnosticPath);
end
baseline = loaded.diagnostics;
if ~isstruct(baseline) || ~isscalar(baseline)
    error('diagnoseResidualFeatureArtifacts:InvalidPrecomputedArtifact', ...
        '已有基线诊断不是标量结构：%s。', diagnosticPath);
end
required = {'beautyMasks', 'mask', 'frequency', 'blemishMap', ...
    'blemish', 'repairResult', 'repair', 'smoothingResult', ...
    'smoothing', 'baseLuminanceResult', 'skinToneResult', ...
    'whiteningResult', 'compose'};
requireDiagnosticFields(baseline, required, '已有基线');
imageSize = size(inputImage, 1:2);
if ~isequal(size(baseline.beautyMasks.skinMask), imageSize) || ...
        ~isequal(double(baseline.beautyMasks.imageSize), [imageSize, 3])
    error('diagnoseResidualFeatureArtifacts:InvalidPrecomputedArtifact', ...
        '已有基线与输入图像尺寸不一致。');
end
fullFaceBox = options.faceBox;
if ~isequal(double(baseline.beautyMasks.faceBox), double(fullFaceBox))
    error('diagnoseResidualFeatureArtifacts:FaceBoxMismatch', ...
        '已有基线的人脸框与固定诊断人脸框不一致。');
end
readExistingRegionRows(regionPath, definitions);
frequency = makePrecomputedFrequency(baseline.frequency, inputImage, ...
    fullFaceBox, imageSize);
baseline.frequency = frequency;
elapsedSeconds = readExistingElapsedSeconds(imageMetricPath);
if isfield(loaded, 'output')
    baselineImage = loaded.output;
elseif isfield(options, 'existingBaselineImagePath') && ...
        ~isempty(options.existingBaselineImagePath)
    baselineImagePath = requireFileOption(options, ...
        'existingBaselineImagePath');
    baselineImage = imread(baselineImagePath);
else
    error('diagnoseResidualFeatureArtifacts:MissingPrecomputedArtifact', ...
        '已有基线 MAT 缺少 output，且未提供已有基线 PNG。');
end
validateExistingBaselineImageValue(baselineImage, imageSize);
sourceContext = loaded.context;
requireDiagnosticFields(sourceContext, ...
    {'skinMask', 'faceSkinMask', 'regions', 'regionConfidence'}, ...
    '已有 Beauty Context');
context = struct( ...
    'skinMask', sourceContext.skinMask, ...
    'faceSkinMask', sourceContext.faceSkinMask, ...
    'regions', sourceContext.regions, ...
    'regionConfidence', sourceContext.regionConfidence);
mode = struct('name', 'original', 'image', inputImage, ...
    'faceBox', fullFaceBox, 'context', context, 'scale', 1, ...
    'precomputedBaseline', baseline, ...
    'precomputedBaselineImage', baselineImage, ...
    'elapsedSeconds', elapsedSeconds);
modes = {mode};
previewScale = 1;
previewFaceBox = fullFaceBox;
detection = struct('orientationDegrees', 0, ...
    'selectedCandidateBox', fullFaceBox, ...
    'usedFullImageParsing', false, 'fullParsingCount', 0, ...
    'candidateAssessment', []);
end

function path = requireFileOption(options, name)
value = options.(name);
if ~ischar(value) && ~(isstring(value) && isscalar(value))
    error('diagnoseResidualFeatureArtifacts:InvalidPrecomputedArtifact', ...
        '%s 必须是文本路径。', name);
end
path = char(value);
if ~isfile(path)
    error('diagnoseResidualFeatureArtifacts:MissingPrecomputedArtifact', ...
        '已有诊断产物不存在：%s。', path);
end
end

function validateExistingBaselineImageValue(image, imageSize)
if ~isa(image, 'uint8') || ~isreal(image) || ndims(image) ~= 3 || ...
        size(image, 3) ~= 3 || ~isequal(size(image, 1:2), imageSize)
    error('diagnoseResidualFeatureArtifacts:InvalidPrecomputedArtifact', ...
        '已有基线输出不是匹配尺寸的 uint8 三通道图像。');
end
end

function frequency = makePrecomputedFrequency(frequency, inputImage, ...
        faceBox, imageSize)
required = {'base', 'mid', 'fine'};
requireDiagnosticFields(frequency, required, '已有频率基线');
sourceYcbcr = rgb2ycbcr(im2double(inputImage));
frequency.sourceLuminance = sourceYcbcr(:, :, 1);
frequency.imageSize = [imageSize, 3];
frequency.faceBox = faceBox;
frequency.faceScale = min(double(faceBox(3:4)));
frequency.reconstructedLuminance = double(frequency.base) + ...
    double(frequency.mid) + double(frequency.fine);
frequency.outputLuminance = frequency.reconstructedLuminance;
frequency.alphaMap = zeros(imageSize);
end

function rows = readExistingRegionRows(path, definitions)
tableValue = readtable(path, 'TextType', 'char');
expectedFields = fieldnames(emptyRegionRow());
if ~all(ismember(expectedFields, tableValue.Properties.VariableNames))
    error('diagnoseResidualFeatureArtifacts:MissingDiagnosticField', ...
        '已有区域诊断表缺少 03 字段。');
end
rows = table2struct(tableValue);
if numel(rows) ~= numel(definitions)
    error('diagnoseResidualFeatureArtifacts:InvalidPrecomputedArtifact', ...
        '已有区域诊断表的 ROI 数量与本票不一致。');
end
for index = 1:numel(definitions)
    matches = find(strcmp({rows.symptom}, definitions(index).name));
    if numel(matches) ~= 1
        error('diagnoseResidualFeatureArtifacts:InvalidPrecomputedArtifact', ...
            '已有区域诊断表缺少唯一 ROI %s。', definitions(index).name);
    end
    row = rows(matches);
    expected = definitions(index).roi;
    actual = [row.roiX, row.roiY, row.roiWidth, row.roiHeight];
    if ~isequal(double(actual), double(expected)) || ...
            ~strcmp(row.mode, 'original')
        error('diagnoseResidualFeatureArtifacts:InvalidPrecomputedArtifact', ...
            '已有区域诊断表的 %s ROI 或模式不匹配。', definitions(index).name);
    end
end
end

function elapsedSeconds = readExistingElapsedSeconds(path)
tableValue = readtable(path, 'TextType', 'char');
required = {'mode', 'elapsedSeconds'};
if ~all(ismember(required, tableValue.Properties.VariableNames))
    error('diagnoseResidualFeatureArtifacts:MissingDiagnosticField', ...
        '已有图像指标表缺少 mode 或 elapsedSeconds。');
end
matches = strcmp(tableValue.mode, 'original');
if nnz(matches) ~= 1
    error('diagnoseResidualFeatureArtifacts:InvalidPrecomputedArtifact', ...
        '已有图像指标表缺少唯一 original 记录。');
end
elapsedSeconds = tableValue.elapsedSeconds(matches);
if ~isfinite(elapsedSeconds) || elapsedSeconds < 0
    error('diagnoseResidualFeatureArtifacts:InvalidPrecomputedArtifact', ...
        '已有基线耗时无效。');
end
end

function options = normalizeOptions(options)
if nargin < 1 || isempty(options) || ~isstruct(options) || ...
        ~isscalar(options)
    error('diagnoseResidualFeatureArtifacts:MissingRoi', ...
        ['必须提供至少一个依据原图或截图人工确定的 ROI；不能由 ', ...
        '待验证的 Mask 自动生成选区。']);
end
roiFields = {'earRoi', 'nostrilRoi', 'browEyeRoi', ...
    'noseBridgeRoi', 'noseWingRoi', 'normalSkinRoi', 'freckleRoi', ...
    'hairRoi', 'backgroundRoi'};
hasRoi = false;
for index = 1:numel(roiFields)
    name = roiFields{index};
    if isfield(options, name) && ~isempty(options.(name))
        options.(name) = validateRoi(options.(name), name);
        hasRoi = true;
    end
end
if isfield(options, 'faceBox') && ~isempty(options.faceBox)
    options.faceBox = validateRoi(options.faceBox, 'faceBox');
end
if ~hasRoi
    error('diagnoseResidualFeatureArtifacts:MissingRoi', ...
        ['必须提供至少一个人工 ROI；ROI 不能由待验证的 ', ...
        '皮肤或保护 Mask 自动生成。']);
end
if ~isfield(options, 'smoothingStrength')
    options.smoothingStrength = 100;
end
if ~isfield(options, 'whiteningStrength')
    options.whiteningStrength = 15;
end
if ~isValidStrength(options.smoothingStrength) || ...
        ~isValidStrength(options.whiteningStrength)
    error('diagnoseResidualFeatureArtifacts:InvalidStrength', ...
        '磨皮和美白强度必须是范围 0 到 100 内的有限数值标量。');
end
end

function image = readInputImage(imagePath)
if ~ischar(imagePath) && ~(isstring(imagePath) && isscalar(imagePath))
    error('diagnoseResidualFeatureArtifacts:InvalidImagePath', ...
        '输入图像路径必须是文本。');
end
imagePath = char(imagePath);
if ~isfile(imagePath)
    error('diagnoseResidualFeatureArtifacts:MissingImage', ...
        '输入图像不存在：%s。', imagePath);
end
image = imread(imagePath);
if ~isa(image, 'uint8') || ~isreal(image) || ndims(image) ~= 3 || ...
        size(image, 3) ~= 3
    error('diagnoseResidualFeatureArtifacts:InvalidImage', ...
        '输入图像必须是 uint8 三通道 RGB 图像。');
end
end

function definitions = makeRegionDefinitions(options)
specs = { ...
    struct('name', 'ear', 'field', 'earRoi', ...
    'semanticNames', {{'leftEar', 'rightEar'}}, 'kind', 'feature'), ...
    struct('name', 'nostril', 'field', 'nostrilRoi', ...
    'semanticNames', {{'nose'}}, 'kind', 'feature'), ...
    struct('name', 'browEye', 'field', 'browEyeRoi', ...
    'semanticNames', {{'leftBrow', 'rightBrow', 'leftEye', 'rightEye'}}, ...
    'kind', 'feature'), ...
    struct('name', 'noseBridge', 'field', 'noseBridgeRoi', ...
    'semanticNames', {{'nose'}}, 'kind', 'structure'), ...
    struct('name', 'noseWing', 'field', 'noseWingRoi', ...
    'semanticNames', {{'nose'}}, 'kind', 'structure'), ...
    struct('name', 'normalSkin', 'field', 'normalSkinRoi', ...
    'semanticNames', {{'skin'}}, 'kind', 'reference'), ...
    struct('name', 'freckle', 'field', 'freckleRoi', ...
    'semanticNames', {{'skin'}}, 'kind', 'reference'), ...
    struct('name', 'hair', 'field', 'hairRoi', ...
    'semanticNames', {{'hair'}}, 'kind', 'safety'), ...
    struct('name', 'background', 'field', 'backgroundRoi', ...
    'semanticNames', {{'background'}}, 'kind', 'safety')};
definitions = struct('name', {}, 'roi', {}, ...
    'semanticNames', {}, 'kind', {});
for index = 1:numel(specs)
    spec = specs{index};
    if ~isfield(options, spec.field) || isempty(options.(spec.field))
        continue;
    end
    definition = struct('name', spec.name, ...
        'roi', options.(spec.field), 'kind', spec.kind);
    definition.semanticNames = spec.semanticNames;
    definitions(end + 1, 1) = definition; %#ok<AGROW>
end
end

function [modeResult, regionRows, ablationRows, repairComponentRows, ...
        repairCombinationRows] = diagnoseMode( ...
        mode, definitions, options)
params = struct('smoothingStrength', options.smoothingStrength, ...
    'whiteningStrength', options.whiteningStrength);
if isfield(mode, 'precomputedBaseline')
    baseline = mode.precomputedBaseline;
    frequency = baseline.frequency;
    processing = makeProcessing(baseline);
    [output, compose] = beauty.composeBeautyResult(mode.image, ...
        frequency, baseline.repairResult, baseline.beautyMasks, ...
        params.whiteningStrength, processing);
    existingDifference = max(abs(double(output) - ...
        double(mode.precomputedBaselineImage)), [], 'all');
    if existingDifference ~= 0
        error('diagnoseResidualFeatureArtifacts:PrecomputedBaselineMismatch', ...
            '已有基线组件重建与保存的 v3.2 输出不一致，最大 RGB 差为 %.17g。', ...
            existingDifference);
    end
    baseline.output = output;
    baseline.compose = compose;
    elapsedSeconds = mode.elapsedSeconds;
else
    startTime = tic;
    [output, baseline] = beautifyImage(mode.image, params, mode.faceBox, ...
        mode.context);
    elapsedSeconds = toc(startTime);
    [frequency, ~] = beauty.decomposeSkinFrequency( ...
        mode.image, mode.faceBox);
end
imageMetrics = evaluateImage(mode.image, output, elapsedSeconds);
baseline.output = output;
required = {'beautyMasks', 'blemishMap', 'smoothingResult', ...
    'repairResult', 'baseLuminanceResult', 'skinToneResult', ...
    'whiteningResult', 'compose'};
if ~all(isfield(baseline, required))
    error('diagnoseResidualFeatureArtifacts:IncompleteDiagnostics', ...
        '基线诊断缺少定位残留五官失真所需的阶段结果。');
end
validateRequiredDiagnostics(baseline, size(mode.image, 1:2));
baseline.frequency = frequency;
structureSources = reconstructStructureSources( ...
    mode.faceBox, baseline.beautyMasks, ...
    baseline.mask.structure);
safetyMasks = buildSafetyMasks(mode.context, definitions, ...
    baseline.beautyMasks);
ablation = runAblations(mode.image, frequency, baseline.beautyMasks, ...
    baseline.blemishMap, baseline, params, definitions);
processing = makeProcessing(baseline);
repairComponents = buildRepairComponents(mode.image, frequency, ...
    baseline, baseline.beautyMasks, params, processing);
repairCombination = measureRepairCombination(repairComponents, mode);

regionRows = repmat(emptyRegionRow(), 0, 1);
ablationRows = repmat(emptyAblationRow(), 0, 1);
repairComponentRows = repmat(emptyRepairComponentRow(), 0, 1);
repairCombinationRows = repmat(emptyRepairCombinationRow(), 0, 1);
for regionIndex = 1:numel(definitions)
    definition = definitions(regionIndex);
    if ~isfield(mode, 'reusedRegionRows')
        regionRows(end + 1, 1) = measureRegion(mode, definition, ...
            baseline.beautyMasks, baseline, structureSources, ...
            safetyMasks); %#ok<AGROW>
    end
    for ablationIndex = 1:numel(ablation.items)
        item = ablation.items(ablationIndex);
        ablationRows(end + 1, 1) = measureAblation(mode, definition, ...
            item, baseline, safetyMasks); %#ok<AGROW>
    end
    if strcmp(definition.kind, 'feature')
        for componentIndex = 1:numel(repairComponents)
            repairComponentRows(end + 1, 1) = measureRepairComponent( ...
                mode, definition, repairComponents(componentIndex), ...
                repairComponents, baseline, safetyMasks); %#ok<AGROW>
        end
    end
end
if isfield(mode, 'reusedRegionRows')
    regionRows = mode.reusedRegionRows;
end
repairCombinationRows(1, 1) = repairCombination;

modeResult = struct( ...
    'name', mode.name, ...
    'image', mode.image, ...
    'faceBox', mode.faceBox, ...
    'context', mode.context, ...
    'definitions', definitions, ...
    'output', output, ...
    'baseline', baseline, ...
    'frequency', frequency, ...
    'structureSources', structureSources, ...
    'ablation', ablation, ...
    'repairComponents', repairComponents, ...
    'repairCombination', repairCombination, ...
    'safetyMasks', safetyMasks, ...
    'imageMetrics', imageMetrics);
end

function structure = reconstructStructureSources(faceBox, beautyMasks, ...
        structureDiagnostics)
required = {'continuousEvidence', 'noseStructure', ...
    'outsideStructure', 'faceBoundary'};
if ~all(isfield(structureDiagnostics, required))
    error('diagnoseResidualFeatureArtifacts:MissingStructureEvidence', ...
        '结构诊断缺少现有生产公式所需的来源证据。');
end
imageSize = size(beautyMasks.skinMask);
skin = readMask(beautyMasks, 'skinMask', imageSize);
face = readMask(beautyMasks, 'faceSkinMask', imageSize);
continuousEvidence = readArray(structureDiagnostics.continuousEvidence, ...
    imageSize, 'continuousEvidence');
faceStructure = min(face, skin) .* continuousEvidence;
sourceNames = {'noseStructure', 'outsideStructure', ...
    'faceStructure', 'faceBoundary'};
sources = struct();
sources.noseStructure = readArray(structureDiagnostics.noseStructure, ...
    imageSize, 'noseStructure');
sources.outsideStructure = readArray( ...
    structureDiagnostics.outsideStructure, imageSize, 'outsideStructure');
sources.faceStructure = faceStructure;
sources.faceBoundary = readArray(structureDiagnostics.faceBoundary, ...
    imageSize, 'faceBoundary');
sourceStack = cat(3, sources.noseStructure, sources.outsideStructure, ...
    sources.faceStructure, sources.faceBoundary);
reconstructed = max(sourceStack, [], 3) .* min(max(skin, 0), 1);
baselineStructure = readMask(beautyMasks, ...
    'structureProtectionMask', imageSize);
[maximumSource, dominant] = max(sourceStack, [], 3);
validSource = maximumSource > 1e-12;
dominant(~validSource) = 0;
tieMask = validSource & ...
    sum(abs(sourceStack - maximumSource) <= 1e-12, 3) > 1;
structure = struct( ...
    'names', {sourceNames}, ...
    'sources', sources, ...
    'sourceStack', sourceStack, ...
