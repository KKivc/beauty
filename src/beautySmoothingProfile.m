function profile = beautySmoothingProfile(smoothingStrength)
%BEAUTYSMOOTHINGPROFILE 返回可解释的 v3 磨皮参数曲线。
%   频率保留率控制普通皮肤，blemishStrength 和 toneStrength 控制
%   有证据的局部修复，outsideFaceStrength 控制脸外皮肤参与量。

if ~isnumeric(smoothingStrength) || ~isreal(smoothingStrength) || ...
        ~isscalar(smoothingStrength) || ~isfinite(smoothingStrength) || ...
        smoothingStrength < 0 || smoothingStrength > 100
    error('beautySmoothingProfile:InvalidStrength', ...
        '磨皮强度必须是范围 0 到 100 内的有限数值标量。');
end

ratio = double(smoothingStrength) / 100;
naturalRatio = min(2 * ratio, .75);
profile = struct( ...
    'fineRetention', 1 - (.55 * naturalRatio ^ .85 - ...
        .25 * naturalRatio ^ 2), ...
    'mediumRetention', 1 - .45 * naturalRatio ^ .65, ...
    'blemishStrength', ratio ^ .85, ...
    'toneStrength', naturalRatio ^ .85, ...
    'outsideFaceStrength', .75 * ratio ^ 2 * (3 - 2 * ratio));
end
