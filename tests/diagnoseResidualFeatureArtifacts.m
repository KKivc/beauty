function ablation = runAblations(inputImage, frequency, beautyMasks, ...
        blemishMap, baseline, params, definitions)
processing = makeProcessing(baseline);
overrideCount = 0;
for index = 1:numel(definitions)
    overrideCount = overrideCount + ...
        (strcmp(definitions(index).kind, 'feature') || ...
        strcmp(definitions(index).kind, 'structure'));
end
items = repmat(emptyAblationItem(), 5 + 2 * overrideCount, 1);
itemIndex = 0;

[output, composeDetails] = beauty.composeBeautyResult(inputImage, ...
    frequency, baseline.smoothingResult, beautyMasks, ...
    params.whiteningStrength, processing);
itemIndex = itemIndex + 1;
items(itemIndex) = makeAblationItem('withoutRepair', output, ...
    false(size(beautyMasks.skinMask)), composeDetails, 'stage');

identityFrequency = makeIdentityFrequency(frequency);
[output, composeDetails] = beauty.composeBeautyResult(inputImage, ...
    frequency, identityFrequency, beautyMasks, ...
    params.whiteningStrength, processing);
itemIndex = itemIndex + 1;
items(itemIndex) = makeAblationItem( ...
    'withoutSmoothingAndRepair', output, ...
    false(size(beautyMasks.skinMask)), composeDetails, 'stage');

noBaseProcessing = processing;
noBaseProcessing.baseLuminance = zeroBaseResult( ...
    processing.baseLuminance, size(beautyMasks.skinMask));
[output, composeDetails] = beauty.composeBeautyResult(inputImage, ...
    frequency, baseline.repairResult, beautyMasks, ...
    params.whiteningStrength, noBaseProcessing);
itemIndex = itemIndex + 1;
items(itemIndex) = makeAblationItem('withoutBaseLuminance', output, ...
    false(size(beautyMasks.skinMask)), composeDetails, 'stage');

noToneProcessing = processing;
noToneProcessing.skinTone = zeroToneResult( ...
    processing.skinTone, inputImage, size(beautyMasks.skinMask));
[output, composeDetails] = beauty.composeBeautyResult(inputImage, ...
    frequency, baseline.repairResult, beautyMasks, ...
    params.whiteningStrength, noToneProcessing);
itemIndex = itemIndex + 1;
items(itemIndex) = makeAblationItem('withoutSkinTone', output, ...
    false(size(beautyMasks.skinMask)), composeDetails, 'stage');

noWhiteningProcessing = processing;
noWhiteningProcessing.whitening = zeroWhiteningResult( ...
    processing.whitening, size(beautyMasks.skinMask));
[output, composeDetails] = beauty.composeBeautyResult(inputImage, ...
    frequency, baseline.repairResult, beautyMasks, ...
    params.whiteningStrength, noWhiteningProcessing);
itemIndex = itemIndex + 1;
items(itemIndex) = makeAblationItem('withoutWhitening', output, ...
    false(size(beautyMasks.skinMask)), composeDetails, 'stage');

for index = 1:numel(definitions)
    definition = definitions(index);
    if ~strcmp(definition.kind, 'feature') && ...
            ~strcmp(definition.kind, 'structure')
        continue;
    end
    scope = regionMask(definition.roi, size(beautyMasks.skinMask));

    textureMasks = beautyMasks;
    textureMasks.textureProtectionMask = max( ...
        readMask(beautyMasks, 'textureProtectionMask', ...
        size(scope)), double(scope));
    [output, details] = runPipelineWithMasks(inputImage, frequency, ...
        textureMasks, blemishMap, params);
    itemIndex = itemIndex + 1;
    items(itemIndex) = makeAblationItem( ...
        ['forceTexture_' definition.name], output, scope, ...
        details.compose, 'protection');

    hardMasks = beautyMasks;
    hardMasks.hardProtectionMask = max( ...
        readMask(beautyMasks, 'hardProtectionMask', size(scope)), ...
        double(scope));
    [output, details] = runPipelineWithMasks(inputImage, frequency, ...
        hardMasks, blemishMap, params);
    itemIndex = itemIndex + 1;
    items(itemIndex) = makeAblationItem( ...
        ['forceHard_' definition.name], output, scope, ...
        details.compose, 'protection');
end
ablation.items = items(1:itemIndex);
end

