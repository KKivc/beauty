end

function value = maxDifference(first, second)
if ~isequal(size(first), size(second))
    value = Inf;
    return;
end
value = max(abs(double(first(:)) - double(second(:))));
end

function image = rebuildRgbWithOriginalChroma(luminance, inputYcbcr)
ycbcr = cat(3, min(max(double(luminance), 0), 1), ...
    inputYcbcr(:, :, 2), inputYcbcr(:, :, 3));
image = im2uint8(ycbcr2rgb(ycbcr));
end

function image = cropImage(image, box)
x1 = box(1);
y1 = box(2);
x2 = min(size(image, 2), x1 + box(3) - 1);
y2 = min(size(image, 1), y1 + box(4) - 1);
if ismatrix(image)
    image = image(y1:y2, x1:x2);
else
    image = image(y1:y2, x1:x2, :);
end
end

