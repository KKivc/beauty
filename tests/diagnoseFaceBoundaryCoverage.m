function [summary, diagnostics] = diagnoseFaceBoundaryCoverage( ...
        imagePath, outputFolder, options)
%DIAGNOSEFACEBOUNDARYCOVERAGE 诊断单张人像的脸缘覆盖缺口。
%   入口固定同一输入、尺寸、参数和人工选区，记录皮肤支持、强度、
%   Fine/Mid 门控、阶段作用量和最终图像变化。单因素消融只在本入口内
%   复制 Mask，不改生产算法、公共 Context 或验收阈值。

projectRoot = fileparts(fileparts(mfilename('fullpath')));
addpath(fullfile(projectRoot, 'src'));
if nargin < 3
    options = [];
end
if nargin < 1 || isempty(imagePath)
    error('diagnoseFaceBoundaryCoverage:MissingImagePath', ...
        '必须提供输入图像路径。');
end
options = normalizeOptions(options);
inputImage = readInputImage(imagePath);
options.faceBoundaryRoi = validateRoiBounds(options.faceBoundaryRoi, ...
    size(inputImage), 'faceBoundaryRoi');
options.controlRoi = validateRoiBounds(options.controlRoi, ...
    size(inputImage), 'controlRoi');

if nargin < 2 || isempty(outputFolder)
    outputFolder = fullfile(tempdir, 'image_beauty_face_boundary_diagnosis');
end
if ~ischar(outputFolder) && ~(isstring(outputFolder) && isscalar(outputFolder))
    error('diagnoseFaceBoundaryCoverage:InvalidOutputFolder', ...
        '输出目录必须是文本路径。');
end
outputFolder = char(outputFolder);
if ~isfolder(outputFolder)
    mkdir(outputFolder);
end

contract = beautyPipelineContract();
[previewImage, previewScale] = makePreview(inputImage);
[previewFaceBox, hasFace, detection] = detectSingleFace(previewImage);
if ~hasFace
    error('diagnoseFaceBoundaryCoverage:NoFace', ...
        '输入图像未检测到可用的语义人脸。');
end
previewContext = prepareBeautyContext(previewImage, previewFaceBox, ...
    detection.selectedParsing, struct('rotationDegrees', ...
    detection.orientationDegrees));
fullFaceBox = scaleFaceBox(previewFaceBox, 1 / previewScale, ...
    size(inputImage));
if previewScale < 1
    fullContext = resizeBeautyContext(previewContext, size(inputImage), ...
        fullFaceBox, inputImage);
else
    fullContext = previewContext;
end

modes = { ...
    struct('name', 'preview', 'image', previewImage, ...
    'faceBox', previewFaceBox, 'context', previewContext, ...
    'scale', previewScale), ...
    struct('name', 'original', 'image', inputImage, ...
    'faceBox', fullFaceBox, 'context', fullContext, 'scale', 1)};

regionRows = repmat(emptyRegionRow(), 0, 1);
ablationRows = repmat(emptyAblationRow(), 0, 1);
modeDiagnostics = cell(1, numel(modes));
for modeIndex = 1:numel(modes)
    mode = modes{modeIndex};
    modeOptions = options;
    modeOptions.faceBoundaryRoi = scaleRoi(options.faceBoundaryRoi, ...
        mode.scale, size(mode.image));
    modeOptions.controlRoi = scaleRoi(options.controlRoi, ...
        mode.scale, size(mode.image));
    [modeResult, currentRegionRows, currentAblationRows] = ...
        diagnoseMode(mode, modeOptions);
    modeDiagnostics{modeIndex} = modeResult;
    regionRows = [regionRows; currentRegionRows]; %#ok<AGROW>
    ablationRows = [ablationRows; currentAblationRows]; %#ok<AGROW>
end

regionMetrics = struct2table(regionRows);
ablationMetrics = struct2table(ablationRows);
sourceRows = repmat(emptySourceRow(), 0, 1);
sourceAblationRows = repmat(emptySourceAblationRow(), 0, 1);
featureRows = repmat(emptyFeatureRow(), 0, 1);
for modeIndex = 1:numel(modeDiagnostics)
    mode = modeDiagnostics{modeIndex};
    sourceRows = [sourceRows; mode.attribution.sourceRows]; %#ok<AGROW>
    sourceAblationRows = [sourceAblationRows; ...
        mode.attribution.sourceAblationRows]; %#ok<AGROW>
    featureRows = [featureRows; mode.attribution.featureRows]; %#ok<AGROW>
end
sourceMetrics = struct2table(sourceRows);
sourceAblationMetrics = struct2table(sourceAblationRows);
featureMetrics = struct2table(featureRows);
paths = writeArtifacts(outputFolder, modeDiagnostics, regionMetrics, ...
    ablationMetrics, sourceMetrics, sourceAblationMetrics, featureMetrics);
summary = struct( ...
    'completed', true, ...
    'contract', contract, ...
    'imagePath', char(imagePath), ...
    'inputSize', size(inputImage), ...
    'previewScale', previewScale, ...
    'previewFaceBox', previewFaceBox, ...
    'originalFaceBox', fullFaceBox, ...
    'orientationDegrees', detection.orientationDegrees, ...
    'parameters', struct( ...
    'smoothingStrength', options.smoothingStrength, ...
    'whiteningStrength', options.whiteningStrength), ...
    'faceBoundaryRoi', options.faceBoundaryRoi, ...
    'controlRoi', options.controlRoi, ...
    'regionMetrics', regionMetrics, ...
    'ablationMetrics', ablationMetrics, ...
    'sourceMetrics', sourceMetrics, ...
    'sourceAblationMetrics', sourceAblationMetrics, ...
    'featureMetrics', featureMetrics, ...
    'diagnosticScope', struct( ...
        'sourceNames', {{'noseStructure', 'outsideStructure', ...
        'faceStructure', 'faceBoundary'}}, ...
        'legacyWholeInputAblationIncluded', ...
        options.includeLegacyAblations, ...
        'frozenAdaptiveStatistics', true, ...
        'repairRecomputationIsPropagation', true), ...
    'paths', paths);
compactModes = compactModeDiagnostics(modeDiagnostics);
diagnostics = struct( ...
    'contract', contract, ...
    'detection', compactDetection(detection), ...
    'modes', {compactModes}, ...
    'paths', paths);
dataPath = fullfile(outputFolder, 'faceBoundaryDiagnosticData.mat');
summary.paths.data = dataPath;
diagnostics.paths.data = dataPath;
clear modeDiagnostics compactModes;
save(dataPath, 'summary', 'diagnostics', '-v7.3');
end

function options = normalizeOptions(options)
if nargin < 1 || isempty(options)
    error('diagnoseFaceBoundaryCoverage:MissingOptions', ...
        ['必须提供 faceBoundaryRoi 和 controlRoi；选区必须依据原图 ', ...
        '或截图人工确定，不能由待验证的 Mask 自动生成。']);
end
if ~isstruct(options) || ~isscalar(options) || ...
        ~all(isfield(options, {'faceBoundaryRoi', 'controlRoi'}))
    error('diagnoseFaceBoundaryCoverage:InvalidOptions', ...
        '选项必须包含 faceBoundaryRoi 和 controlRoi。');
end
options.faceBoundaryRoi = validateRoi(options.faceBoundaryRoi, ...
    'faceBoundaryRoi');
options.controlRoi = validateRoi(options.controlRoi, 'controlRoi');
if ~isfield(options, 'smoothingStrength')
    options.smoothingStrength = 100;
end
if ~isfield(options, 'whiteningStrength')
    options.whiteningStrength = 15;
end
if ~isfield(options, 'includeLegacyAblations')
    options.includeLegacyAblations = false;
end
if ~isValidStrength(options.smoothingStrength) || ...
        ~isValidStrength(options.whiteningStrength)
    error('diagnoseFaceBoundaryCoverage:InvalidStrength', ...
        '磨皮和美白强度必须是范围 0 到 100 内的有限数值标量。');
end
if ~islogical(options.includeLegacyAblations) || ...
        ~isscalar(options.includeLegacyAblations)
    error('diagnoseFaceBoundaryCoverage:InvalidOptions', ...
        'includeLegacyAblations 必须是逻辑标量。');
end
end

function image = readInputImage(imagePath)
if ~ischar(imagePath) && ~(isstring(imagePath) && isscalar(imagePath))
    error('diagnoseFaceBoundaryCoverage:InvalidImagePath', ...
        '输入图像路径必须是文本。');
end
imagePath = char(imagePath);
if ~isfile(imagePath)
    error('diagnoseFaceBoundaryCoverage:MissingImage', ...
        '输入图像不存在：%s。', imagePath);
end
image = imread(imagePath);
if ~isa(image, 'uint8') || ~isreal(image) || ndims(image) ~= 3 || ...
        size(image, 3) ~= 3
    error('diagnoseFaceBoundaryCoverage:InvalidImage', ...
        '输入图像必须是 uint8 三通道 RGB 图像。');
end
end

function [modeResult, regionRows, ablationRows] = diagnoseMode(mode, options)
params = struct('smoothingStrength', options.smoothingStrength, ...
    'whiteningStrength', options.whiteningStrength);
[output, baseline] = beautifyImage(mode.image, params, mode.faceBox, ...
    mode.context);
baseline.output = output;
required = {'beautyMasks', 'blemishMap', 'smoothingResult', ...
    'repairResult', 'baseLuminanceResult', 'skinToneResult', ...
    'whiteningResult', 'compose'};
if ~all(isfield(baseline, required))
    error('diagnoseFaceBoundaryCoverage:IncompleteDiagnostics', ...
        '基线诊断缺少可定位脸缘作用量所需的阶段结果。');
end

[frequency, ~] = beauty.decomposeSkinFrequency(mode.image, mode.faceBox);
baseline.frequencyForDiagnosis = frequency;
beautyMasks = baseline.beautyMasks;
blemishMap = baseline.blemishMap;
if options.includeLegacyAblations
    ablation = runAblations(mode.image, frequency, beautyMasks, ...
        blemishMap, baseline, params);
else
    ablation = emptyLegacyAblation(size(mode.image, 1:2));
end
safetyMasks = buildSafetyMasks(mode.context, beautyMasks);
mode.faceBoundaryRoi = options.faceBoundaryRoi;
mode.controlRoi = options.controlRoi;
[attribution, sourceRows, sourceAblationRows, featureRows] = ...
    runStructureAttribution(mode, frequency, beautyMasks, blemishMap, ...
    baseline, params, safetyMasks);
regionDefinitions = { ...
    struct('name', 'faceBoundary', 'roi', options.faceBoundaryRoi), ...
    struct('name', 'control', 'roi', options.controlRoi)};
regionRows = repmat(emptyRegionRow(), 0, 1);
ablationRows = repmat(emptyAblationRow(), 0, 1);
for regionIndex = 1:numel(regionDefinitions)
    region = regionDefinitions{regionIndex};
    regionRows(end + 1, 1) = measureRegion( ...
        mode, region, beautyMasks, baseline, ablation, frequency); %#ok<AGROW>
    for ablationIndex = 1:numel(ablation.items)
        ablationRows(end + 1, 1) = measureAblation( ...
            mode, region, ablation.items(ablationIndex), ...
            baseline, safetyMasks); %#ok<AGROW>
    end
end

modeResult = struct( ...
    'name', mode.name, ...
    'image', mode.image, ...
    'faceBox', mode.faceBox, ...
    'context', mode.context, ...
    'faceBoundaryRoi', options.faceBoundaryRoi, ...
    'controlRoi', options.controlRoi, ...
    'output', output, ...
    'baseline', baseline, ...
    'frequency', frequency, ...
    'ablation', ablation, ...
    'attribution', struct( ...
        'sourceRows', sourceRows, ...
        'sourceAblationRows', sourceAblationRows, ...
        'featureRows', featureRows, ...
        'details', attribution), ...
    'safetyMasks', safetyMasks);
end

function ablation = emptyLegacyAblation(imageSize)
%EMPTYLEGACYABLATION 04 默认不重复执行 02 的整体输入消融。
%   保留与旧结果相同的字段形状，便于复用原有区域表和紧凑诊断；
%   空值明确表示本次没有运行旧实验，而不是把零当作测量结果。
ablation = struct( ...
    'items', repmat(emptyAblationItem(), 0, 1), ...
    'midWithoutRepeated', struct('suppression', nan(imageSize)));
end

function item = emptyAblationItem
item = struct( ...
    'name', '', 'output', uint8([]), 'smoothing', struct(), ...
    'repair', struct(), 'smoothingDetails', struct(), ...
    'repairDetails', struct(), 'compose', struct());
end

function ablation = runAblations(inputImage, frequency, beautyMasks, ...
        blemishMap, baseline, params)
processing = struct( ...
    'baseLuminance', baseline.baseLuminanceResult, ...
    'skinTone', baseline.skinToneResult, ...
    'whitening', baseline.whiteningResult);
originalSmoothing = baseline.smoothingResult;

withoutStructureMasks = beautyMasks;
withoutStructureMasks.structureProtectionMask = zeros( ...
    size(beautyMasks.structureProtectionMask));
[withoutStructureSmoothing, smoothingDetails] = ...
    beauty.smoothSkinTexture(frequency, withoutStructureMasks, ...
    params.smoothingStrength, blemishMap);
[withoutStructureRepair, repairDetails] = ...
    beauty.repairSkinBlemishes(withoutStructureSmoothing, beautyMasks, ...
    blemishMap, params.smoothingStrength);
[withoutStructureOutput, composeDetails] = ...
    composeAblation(inputImage, frequency, withoutStructureRepair, ...
    beautyMasks, params.whiteningStrength, processing);
items(1) = makeAblationItem('smoothingWithoutStructure', ...
    withoutStructureOutput, withoutStructureSmoothing, ...
    withoutStructureRepair, smoothingDetails, repairDetails, composeDetails);

[repairWithoutStructure, repairDetails] = ...
    beauty.repairSkinBlemishes(originalSmoothing, withoutStructureMasks, ...
    blemishMap, params.smoothingStrength);
[repairWithoutStructureOutput, composeDetails] = ...
    composeAblation(inputImage, frequency, repairWithoutStructure, ...
    beautyMasks, params.whiteningStrength, processing);
items(2) = makeAblationItem('repairWithoutStructure', ...
    repairWithoutStructureOutput, originalSmoothing, repairWithoutStructure, ...
    struct(), repairDetails, composeDetails);

withoutTextureMasks = beautyMasks;
withoutTextureMasks.textureProtectionMask = zeros( ...
    size(beautyMasks.textureProtectionMask));
[repairWithoutTexture, repairDetails] = ...
    beauty.repairSkinBlemishes(originalSmoothing, withoutTextureMasks, ...
    blemishMap, params.smoothingStrength);
[repairWithoutTextureOutput, composeDetails] = ...
    composeAblation(inputImage, frequency, repairWithoutTexture, ...
    beautyMasks, params.whiteningStrength, processing);
items(3) = makeAblationItem('repairWithoutTexture', ...
    repairWithoutTextureOutput, originalSmoothing, repairWithoutTexture, ...
    struct(), repairDetails, composeDetails);

% 这里只移除 Mid 的第二次结构门控，用于判断 gate^2 是否真的贡献了
% 当前选区的抑制；不把该对照接入生产结果。
midGate = baseline.smoothing.midStructureGate;
midAlphaWithoutRepeated = baseline.smoothing.alphaMap .* ...
    baseline.smoothing.noseMidGate;
midRetentionWithoutRepeated = 1 - midAlphaWithoutRepeated .* ...
    (1 - baseline.smoothing.midRetention);
midWithoutRepeated = frequency.mid .* midRetentionWithoutRepeated;
ablation.midWithoutRepeated = struct( ...
    'midStructureGate', midGate, ...
    'midAlphaMap', midAlphaWithoutRepeated, ...
    'mid', midWithoutRepeated, ...
    'suppression', abs(midAlphaWithoutRepeated - ...
    baseline.smoothing.midAlphaMap));
[repairWithoutRepeated, repairDetails] = ...
    beauty.repairSkinBlemishes( ...
    replaceSmoothingMid(originalSmoothing, midWithoutRepeated, ...
    midAlphaWithoutRepeated, midRetentionWithoutRepeated), beautyMasks, ...
    blemishMap, params.smoothingStrength);
[repairWithoutRepeatedOutput, composeDetails] = ...
    composeAblation(inputImage, frequency, repairWithoutRepeated, ...
    beautyMasks, params.whiteningStrength, processing);
items(4) = makeAblationItem('smoothingWithoutRepeatedMid', ...
    repairWithoutRepeatedOutput, ...
    replaceSmoothingMid(originalSmoothing, midWithoutRepeated, ...
    midAlphaWithoutRepeated, midRetentionWithoutRepeated), ...
    repairWithoutRepeated, struct(), repairDetails, composeDetails);
ablation.items = items;
end

function smoothed = replaceSmoothingMid(original, mid, alphaMap, retentionMap)
smoothed = original;
smoothed.mid = mid;
smoothed.midAlphaMap = alphaMap;
smoothed.midRetentionMap = retentionMap;
smoothed.mediumRetentionMap = retentionMap;
smoothed.actualMidRetentionMap = retentionMap;
smoothed.actualMediumRetentionMap = retentionMap;
smoothed.midActualRetentionMap = retentionMap;
smoothed.reconstructedLuminance = original.base + mid + original.fine;
smoothed.outputLuminance = smoothed.reconstructedLuminance;
end

function item = makeAblationItem(name, output, smoothing, repair, ...
        smoothingDetails, repairDetails, composeDetails)
item = struct( ...
    'name', name, ...
    'output', output, ...
    'smoothing', smoothing, ...
    'repair', repair, ...
    'smoothingDetails', smoothingDetails, ...
    'repairDetails', repairDetails, ...
    'compose', composeDetails);
end

function [output, diagnostics] = composeAblation(inputImage, frequency, ...
        repairedFrequency, beautyMasks, whiteningStrength, processing)
[output, diagnostics] = beauty.composeBeautyResult(inputImage, frequency, ...
    repairedFrequency, beautyMasks, whiteningStrength, processing);
end

function [attribution, sourceRows, sourceAblationRows, featureRows] = ...
        runStructureAttribution(mode, frequency, beautyMasks, blemishMap, ...
        baseline, params, safetyMasks)
%RUNSTRUCTUREATTRIBUTION 归因四个现有结构保护来源及其局部消融。
%   来源分解严格复现生产端的 max(...)*skin 顺序。消融只在诊断入口
%   替换一个来源，再使用基线的自适应保留率；Repair 的再次计算只作为
%   下游传播结果记录，不把它误写成单纯门控效果。
structure = extractStructureSources(mode, baseline, beautyMasks);
[frozenBaseline, ~] = buildFrozenSmoothing( ...
    frequency, beautyMasks, baseline.smoothing, structure.finalProtection);
frozenBaselineErrors = [ ...
    abs(frozenBaseline.fine(:) - baseline.smoothingResult.fine(:)); ...
    abs(frozenBaseline.mid(:) - baseline.smoothingResult.mid(:)); ...
    abs(frozenBaseline.outputLuminance(:) - ...
    baseline.smoothingResult.outputLuminance(:))];
frozenBaselineError = max(frozenBaselineErrors);
if frozenBaselineError > 1e-12
    error('diagnoseFaceBoundaryCoverage:FrozenBaselineMismatch', ...
        ['冻结基线重建误差为 %.17g，不能在未确认保留率和 ', ...
        '自适应统计一致性前继续做来源归因。'], frozenBaselineError);
end
structure.frozenBaselineMaxError = frozenBaselineError;

sourceNames = structure.sourceNames;
sourceRows = repmat(emptySourceRow(), 0, 1);
sourceAblationRows = repmat(emptySourceAblationRow(), 0, 1);
featureRows = repmat(emptyFeatureRow(), 0, 1);
regionDefinitions = { ...
    struct('name', 'faceBoundary', 'roi', mode.faceBoundaryRoi), ...
    struct('name', 'control', 'roi', mode.controlRoi)};
for regionIndex = 1:numel(regionDefinitions)
    region = regionDefinitions{regionIndex};
    subsets = buildSourceSubsets(mode, region, beautyMasks, baseline);
    for subsetIndex = 1:numel(subsets)
        subset = subsets(subsetIndex);
        for sourceIndex = 1:numel(sourceNames)
            sourceRows(end + 1, 1) = measureSource( ...
                mode, region, subset, sourceIndex, structure); %#ok<AGROW>
        end
    end
end

[featureMasks, featureDefinitions] = buildFeatureMasks( ...
    mode.context, safetyMasks);
sourceItems = repmat(emptySourceAblationItem(), 0, 1);
for sourceIndex = 1:numel(sourceNames)
    item = runSourceAblation(mode, frequency, beautyMasks, blemishMap, ...
        baseline, params, structure, sourceIndex);
    sourceItems(sourceIndex, 1) = item;
    for regionIndex = 1:numel(regionDefinitions)
        region = regionDefinitions{regionIndex};
        subsets = buildSourceSubsets(mode, region, beautyMasks, baseline);
        sourceAblationRows(end + 1, 1) = measureSourceAblation( ...
            mode, region, subsets(1), item, baseline, structure, ...
            safetyMasks); %#ok<AGROW>
    end
    currentFeatureRows = measureFeatureRows(mode, sourceNames{sourceIndex}, ...
        item, baseline, featureMasks, featureDefinitions, ...
        structure.lowPassSigma);
    featureRows = [featureRows; currentFeatureRows]; %#ok<AGROW>
end

attribution = struct( ...
    'sourceNames', {sourceNames}, ...
    'structure', structure, ...
    'sourceAblations', sourceItems, ...
    'featureMasks', featureMasks, ...
    'featureDefinitions', featureDefinitions, ...
    'sourceRows', sourceRows, ...
    'sourceAblationRows', sourceAblationRows, ...
    'featureRows', featureRows, ...
    'measurement', struct( ...
        'analysisRule', ['优先使用 ROI ∩ faceSkinMask >= 0.35；若该 ', ...
        '交集为空，改用 ROI ∩ skinMask >= 0.05。'], ...
        'gateZeroRule', 'gate <= 1e-12。', ...
        'gatePartialRule', '1e-12 < gate < 1 - 1e-12。', ...
        'dominanceRule', ['仅在最大最终来源值大于 1e-12 的像素上统计；', ...
        '并列最大值按并列项数等分主导权，唯一最大项另行记录。'], ...
        'energyRule', ['输入频率能量为 0 或选区为空时保留 NaN，', ...
        '不添加分母常数。'], ...
        'ablationRule', ['只移除一个来源并冻结基线自适应统计和保留率；', ...
        'Repair 使用消融后的结构 Mask 重新计算，作为传播后果。']));
end

function structure = extractStructureSources(mode, baseline, beautyMasks)
if ~isfield(baseline, 'mask') || ~isstruct(baseline.mask) || ...
        ~isfield(baseline.mask, 'structure')
    error('diagnoseFaceBoundaryCoverage:MissingStructureDiagnostics', ...
        '基线缺少结构保护来源诊断，不能进行来源归因。');
end
details = baseline.mask.structure;
required = {'continuousEvidence', 'noseStructure', ...
    'outsideStructure', 'faceBoundary', 'lowFrequency', ...
    'lowPassSigma', 'gradientMagnitude', 'orientationCoherence'};
if ~all(isfield(details, required))
    error('diagnoseFaceBoundaryCoverage:MissingStructureDiagnostics', ...
        '结构诊断缺少四来源重建所需字段。');
end
imageSize = size(mode.image, 1:2);
skin = readDiagnosticMap(beautyMasks.skinMask, imageSize, 'skinMask');
face = readDiagnosticMap(beautyMasks.faceSkinMask, imageSize, ...
    'faceSkinMask');
continuousEvidence = readDiagnosticMap(details.continuousEvidence, ...
    imageSize, 'continuousEvidence');
noseStructure = readDiagnosticMap(details.noseStructure, imageSize, ...
    'noseStructure');
outsideStructure = readDiagnosticMap(details.outsideStructure, imageSize, ...
    'outsideStructure');
faceBoundary = readDiagnosticMap(details.faceBoundary, imageSize, ...
    'faceBoundary');
% 生产端未把 faceStructure 放进公共诊断字段；在本入口按同一公式复算。
faceStructure = min(face, skin) .* continuousEvidence;
sourceNames = {'noseStructure', 'outsideStructure', ...
    'faceStructure', 'faceBoundary'};
rawSources = cat(3, noseStructure, outsideStructure, ...
    faceStructure, faceBoundary);
skinSupport = min(max(skin, 0), 1);
effectiveSources = rawSources .* skinSupport;
maxSource = max(rawSources, [], 3);
reconstructed = maxSource .* skinSupport;
baselineProtection = readDiagnosticMap( ...
    beautyMasks.structureProtectionMask, imageSize, ...
    'structureProtectionMask');
reconstructionError = reconstructed - baselineProtection;
maxAbsError = max(abs(reconstructionError(:)));
meanAbsError = mean(abs(reconstructionError(:)));
if maxAbsError > 1e-12
    error('diagnoseFaceBoundaryCoverage:StructureReconstructionMismatch', ...
        ['四来源按生产顺序重建的保护图与基线不一致：最大误差 %.17g，', ...
        '平均误差 %.17g。已停止归因。'], maxAbsError, meanAbsError);
end

tieTolerance = 1e-12;
activeMask = max(effectiveSources, [], 3) > tieTolerance;
winnerMask = false(size(effectiveSources));
maximum = max(effectiveSources, [], 3);
for sourceIndex = 1:numel(sourceNames)
    winnerMask(:, :, sourceIndex) = activeMask & ...
        abs(effectiveSources(:, :, sourceIndex) - maximum) <= ...
        tieTolerance;
end
tieCount = sum(winnerMask, 3);
dominanceWeights = zeros(size(effectiveSources));
dominantMask = false(size(effectiveSources));
dominantIndex = zeros(imageSize);
for sourceIndex = 1:numel(sourceNames)
    dominanceWeights(:, :, sourceIndex) = double( ...
        winnerMask(:, :, sourceIndex)) ./ max(tieCount, 1);
    dominantMask(:, :, sourceIndex) = winnerMask(:, :, sourceIndex) & ...
        tieCount == 1;
    dominantIndex(dominantMask(:, :, sourceIndex)) = sourceIndex;
end
tieMask = activeMask & tieCount > 1;

inputY = rgb2ycbcr(im2double(mode.image));
inputLuminance = inputY(:, :, 1);
[inputGradientX, inputGradientY] = gradient(inputLuminance);
inputGradientMagnitude = hypot(inputGradientX, inputGradientY);
contrastSigma = max(1.5, double(details.lowPassSigma));
lowFrequency = readDiagnosticMap(details.lowFrequency, imageSize, ...
    'lowFrequency');
localLowFrequency = imgaussfilt(lowFrequency, ...
    contrastSigma, 'Padding', 'replicate');
lowFrequencyContrast = abs(lowFrequency - ...
    localLowFrequency);
structure = struct( ...
    'sourceNames', {sourceNames}, ...
    'rawSources', rawSources, ...
    'effectiveSources', effectiveSources, ...
    'maxSource', maxSource, ...
    'finalProtection', reconstructed, ...
    'baselineProtection', baselineProtection, ...
    'reconstructionError', reconstructionError, ...
    'reconstructionMaxAbsError', maxAbsError, ...
    'reconstructionMeanAbsError', meanAbsError, ...
    'skinSupport', skinSupport, ...
    'activeMask', activeMask, ...
    'winnerMask', winnerMask, ...
    'dominantMask', dominantMask, ...
