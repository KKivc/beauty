function components = buildRepairComponents(inputImage, frequency, ...
        baseline, beautyMasks, params, processing)
smoothed = baseline.smoothingResult;
repairFrequency = baseline.repairResult;
repairDiagnostics = baseline.repair;
imageSize = size(inputImage, 1:2);
requireDiagnosticFields(smoothed, {'base', 'mid', 'fine', ...
    'outputLuminance', 'alphaMap'}, '平滑结果');
requireDiagnosticFields(repairFrequency, {'base', 'mid', 'fine', ...
    'outputLuminance', 'alphaMap'}, 'Repair 结果');
requireDiagnosticFields(repairDiagnostics, {'fineAfter', 'midAfter', ...
    'fineWeight', 'mediumWeight'}, 'Repair 诊断');
readArray(smoothed.base, imageSize, '平滑 Base');
readArray(smoothed.mid, imageSize, '平滑 Mid');
readArray(smoothed.fine, imageSize, '平滑 Fine');
readArray(repairDiagnostics.fineAfter, imageSize, 'Repair Fine');
readArray(repairDiagnostics.midAfter, imageSize, 'Repair Mid');
readArray(repairDiagnostics.fineWeight, imageSize, 'Repair Fine 权重');
readArray(repairDiagnostics.mediumWeight, imageSize, 'Repair Mid 权重');

names = {'completeRepair', 'fineOnly', 'midOnly', 'withoutRepair'};
components = repmat(emptyRepairComponentItem(), numel(names), 1);
for index = 1:numel(names)
    name = names{index};
    componentFrequency = makeRepairComponentFrequency( ...
        smoothed, repairFrequency, repairDiagnostics, name, imageSize);
    [output, compose] = beauty.composeBeautyResult(inputImage, ...
        frequency, componentFrequency, beautyMasks, ...
        params.whiteningStrength, processing);
    components(index) = makeRepairComponent(name, componentFrequency, ...
        output, compose, smoothed);
end

baselineDifference = max(abs(double(components(1).output) - ...
    double(baseline.output)), [], 'all');
components(1).baselineDifferenceMax = baselineDifference;
if baselineDifference ~= 0
    error('diagnoseResidualFeatureArtifacts:RepairReconstructionMismatch', ...
        '完整 Repair 重建与同一基线输出不一致，最大 RGB 差为 %.17g。', ...
        baselineDifference);
end
end

function componentFrequency = makeRepairComponentFrequency( ...
        smoothed, repairFrequency, repairDiagnostics, name, imageSize)
switch name
    case 'completeRepair'
        componentFrequency = repairFrequency;
    case 'fineOnly'
        componentFrequency = smoothed;
        componentFrequency.fine = repairDiagnostics.fineAfter;
        componentFrequency.alphaMap = min(1, max(double(smoothed.alphaMap), ...
            double(repairDiagnostics.fineWeight)));
    case 'midOnly'
        componentFrequency = smoothed;
        componentFrequency.mid = repairDiagnostics.midAfter;
        componentFrequency.alphaMap = min(1, max(double(smoothed.alphaMap), ...
            double(repairDiagnostics.mediumWeight)));
    case 'withoutRepair'
        componentFrequency = smoothed;
    otherwise
        error('diagnoseResidualFeatureArtifacts:InvalidRepairComponent', ...
            '未知 Repair 分量 %s。', name);
end
componentFrequency.reconstructedLuminance = double( ...
    componentFrequency.base) + double(componentFrequency.mid) + ...
    double(componentFrequency.fine);
componentFrequency.outputLuminance = ...
    componentFrequency.reconstructedLuminance;
if ~isequal(size(componentFrequency.outputLuminance), imageSize)
    error('diagnoseResidualFeatureArtifacts:InvalidRepairComponent', ...
        'Repair 分量 %s 的输出尺寸不匹配。', name);
end
end

function item = makeRepairComponent(name, frequency, output, compose, ...
        smoothed)
item = emptyRepairComponentItem();
item.name = name;
item.frequency = frequency;
item.output = output;
item.compose = compose;
item.fineCorrection = double(frequency.fine) - double(smoothed.fine);
item.mediumCorrection = double(frequency.mid) - double(smoothed.mid);
end

function row = measureRepairComponent(mode, definition, component, ...
        components, baseline, safetyMasks)
imageSize = size(mode.image, 1:2);
roi = regionMask(definition.roi, imageSize);
withoutRepair = findRepairComponent(components, 'withoutRepair');
smoothed = baseline.smoothingResult;
fine = readArray(component.frequency.fine, imageSize, ...
    [component.name ' Fine']);
mid = readArray(component.frequency.mid, imageSize, ...
    [component.name ' Mid']);
smoothFine = readArray(smoothed.fine, imageSize, '平滑 Fine');
smoothMid = readArray(smoothed.mid, imageSize, '平滑 Mid');
fineAction = abs(fine - smoothFine);
midAction = abs(mid - smoothMid);
blemishMap = readArray(baseline.blemishMap, imageSize, 'blemishMap');
energyBefore = (abs(smoothFine) + abs(smoothMid)) .* blemishMap;
energyAfter = (abs(fine) + abs(mid)) .* blemishMap;
outputChange = max(abs(double(component.output) - ...
    double(mode.image)), [], 3);
outputDifference = max(abs(double(component.output) - ...
    double(withoutRepair.output)), [], 3);
componentY = rgb2ycbcr(im2double(component.output));
withoutRepairY = rgb2ycbcr(im2double(withoutRepair.output));
base = readArray(smoothed.base, imageSize, '平滑 Base');
beforeGradient = lowFrequencyGradient(base + smoothMid);
afterGradient = lowFrequencyGradient(base + mid);

row = emptyRepairComponentRow();
row.mode = mode.name;
row.symptom = definition.name;
row.component = component.name;
row.roiX = definition.roi(1);
row.roiY = definition.roi(2);
row.roiWidth = definition.roi(3);
row.roiHeight = definition.roi(4);
row.roiPixels = nnz(roi);
row.fineActionMean = meanOn(fineAction, roi);
row.fineActionP90 = percentileOn(fineAction, roi, .90);
row.fineActiveFraction = fractionOf(fineAction > 1e-6, roi);
row.midActionMean = meanOn(midAction, roi);
row.midActionP90 = percentileOn(midAction, roi, .90);
row.midActiveFraction = fractionOf(midAction > 1e-6, roi);
row.fineRetentionRatio = safeRatio(meanOn(abs(fine), roi), ...
    meanOn(abs(smoothFine), roi));
row.midRetentionRatio = safeRatio(meanOn(abs(mid), roi), ...
    meanOn(abs(smoothMid), roi));
row.blemishEnergyBeforeMean = meanOn(energyBefore, roi);
row.blemishEnergyAfterMean = meanOn(energyAfter, roi);
row.blemishEnergyReductionRatio = 1 - safeRatio( ...
    row.blemishEnergyAfterMean, row.blemishEnergyBeforeMean);
row.outputRgbChangeFromInputMean = meanOn(outputChange, roi);
row.outputRgbChangeFromInputP90 = percentileOn(outputChange, roi, .90);
row.outputRgbChangeFromInputMax = maxOn(outputChange, roi);
row.outputRgbDifferenceFromNoRepairMean = meanOn(outputDifference, roi);
row.outputRgbDifferenceFromNoRepairP90 = percentileOn( ...
    outputDifference, roi, .90);
row.outputRgbDifferenceFromNoRepairMax = maxOn(outputDifference, roi);
row.outputLuminanceDifferenceFromNoRepairMean = meanOn( ...
    abs(componentY(:, :, 1) - withoutRepairY(:, :, 1)), roi);
row.lowFrequencyGradientBeforeMean = meanOn(beforeGradient, roi);
row.lowFrequencyGradientAfterMean = meanOn(afterGradient, roi);
row.lowFrequencyGradientRetentionRatio = safeRatio( ...
    row.lowFrequencyGradientAfterMean, row.lowFrequencyGradientBeforeMean);
row.hardProtectionMaxRgbChange = maxOn(outputChange, safetyMasks.hard);
row.hairMaxRgbChange = maxOn(outputChange, safetyMasks.hair);
row.backgroundMaxRgbChange = maxOn(outputChange, safetyMasks.background);
end

function row = measureRepairCombination(components, mode)
