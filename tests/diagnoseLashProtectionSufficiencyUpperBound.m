function [summary, diagnostics] = diagnoseLashProtectionSufficiencyUpperBound( ...
        imagePath, outputFolder, options)
%DIAGNOSELASHPROTECTIONSUFFICIENCYUPPERBOUND 验证 Issue 08.5。
%   固定复用 Issue 08.4 的 77.png、人工真值、faceBox、browEye、lashRoi
%   和当前生产链。Baseline/Candidate 由 Issue 08.4 诊断入口生成；本入口
%   只在 Candidate 已有 lashProtection support 内把强度提升到 1，随后重跑
%   当前已有 Smoothing、Repair 和 compose。不得修改 src/。
%
%   [summary, diagnostics] = diagnoseLashProtectionSufficiencyUpperBound( ...
%       'E:\image_beauty\人脸\人脸\77.png', tempdir, struct(...
%       'productionRoot', 'E:\image_beauty', ...
%       'baselinePath', ...
%       'C:\Users\JJiio\AppData\Local\Temp\image_beauty_issue02_probe\77_v32_probe.mat'));

projectRoot = fileparts(fileparts(mfilename('fullpath')));
if nargin < 2
    outputFolder = [];
end
if nargin < 3
    options = [];
end
options = normalizeOptions(options, projectRoot);

productionRoot = resolveProductionRoot(options.productionRoot);
addpath(fullfile(productionRoot, 'src'), '-begin');
addpath(fileparts(mfilename('fullpath')), '-begin');

if nargin < 1 || isempty(imagePath)
    error('diagnoseLashProtectionSufficiencyUpperBound:MissingImage', ...
        '必须提供固定 77.png 的输入图像路径。');
end
imagePath = normalizeText(imagePath, 'imagePath');
outputFolder = normalizeOutputFolder(outputFolder);
inputImage = readInputImage(imagePath);
validateCommonFixtureShape(inputImage, options);

% 先由 Issue 08.4 入口完成同一生产基线和 Candidate。manualLashMask
% 在该入口内仅用于验收统计，未进入 Candidate 的任何计算路径。
stageFolder = tempname;
mkdir(stageFolder);
[continuitySummary, continuityDiagnostics] = ...
    diagnoseLashSoftContinuityCandidate(imagePath, stageFolder, options);
if ~continuitySummary.completed || ...
        ~strcmp(continuitySummary.issue, '08.4') || ...
        continuitySummary.runtimeCacheReused
    error('diagnoseLashProtectionSufficiencyUpperBound:InvalidContinuityStage', ...
        'Issue 08.4 基线阶段未按无缓存固定链完成。');
end

manualLashMask = continuityDiagnostics.manualLashMask;
annotation = continuityDiagnostics.annotation;
imageSize = [size(inputImage, 1), size(inputImage, 2)];
if ~annotation.diagnosticsIndependent || ~annotation.fixedAfterAnnotation
    error('diagnoseLashProtectionSufficiencyUpperBound:InvalidManualTruth', ...
        'manualLashMask 必须声明为独立且固定的人工真值。');
end

inputParams = struct('smoothingStrength', options.smoothingStrength, ...
    'whiteningStrength', options.whiteningStrength);
frequency = continuityDiagnostics.frequency;
blemishMap = continuityDiagnostics.blemishMap;
baselineBeautyMasks = continuityDiagnostics.baselineBeautyMasks;
candidateBeautyMasks = continuityDiagnostics.candidateBeautyMasks;
baselineTextureDiagnostics = continuityDiagnostics.baselineTextureDiagnostics;
candidateTextureDiagnostics = continuityDiagnostics.candidateTextureDiagnostics;
baselineLashProtection = continuityDiagnostics.baselineLashProtection;
candidateLashProtection = continuityDiagnostics.candidateLashProtection;
baselineTextureProtectionMask = double( ...
    baselineBeautyMasks.textureProtectionMask);
candidateTextureProtectionMask = double( ...
    candidateBeautyMasks.textureProtectionMask);

validateCommonFixture(continuitySummary, annotation, inputImage, options);
validateArray(candidateLashProtection, imageSize, 'candidateLashProtection');
validateArray(baselineLashProtection, imageSize, 'baselineLashProtection');
validateMask(baselineTextureProtectionMask, imageSize, ...
    'baselineTextureProtectionMask');
validateMask(candidateTextureProtectionMask, imageSize, ...
    'candidateTextureProtectionMask');

% Upper Bound 的唯一变量：Candidate lashProtection 已经非零的位置。
% 这里不使用 manualLashMask、dilation、第二次 closing 或任何新 support。
candidateSupport = candidateLashProtection > 0;
upperBoundLashProtection = candidateLashProtection;
upperBoundLashProtection(candidateSupport) = 1;
upperBoundSupport = upperBoundLashProtection > 0;
supportChangedPixels = nnz(xor(candidateSupport, upperBoundSupport));
if supportChangedPixels ~= 0
    error('diagnoseLashProtectionSufficiencyUpperBound:SupportChanged', ...
        'Upper Bound 改变了 Candidate lashProtection 的 support。');
end

periocularProtection = readDiagnosticArray( ...
    baselineTextureDiagnostics.periocularProtection, imageSize, ...
    'periocularProtection');
doubleEyelidProtection = readDiagnosticArray( ...
    baselineTextureDiagnostics.doubleEyelidProtection, imageSize, ...
    'doubleEyelidProtection');
upperBoundEyeDetailProtection = max(cat(3, periocularProtection, ...
    upperBoundLashProtection, doubleEyelidProtection), [], 3);
upperBoundTextureProtectionMask = max(baselineTextureProtectionMask, ...
    upperBoundEyeDetailProtection);
upperBoundTextureProtectionMask = min(max(upperBoundTextureProtectionMask, ...
    0), 1);
validateMask(upperBoundTextureProtectionMask, imageSize, ...
    'upperBoundTextureProtectionMask');

candidateIncreaseOutsideSupport = ...
    abs(upperBoundTextureProtectionMask - candidateTextureProtectionMask) ...
    > options.formulaTolerance & ~candidateSupport;
if any(candidateIncreaseOutsideSupport(:))
    error('diagnoseLashProtectionSufficiencyUpperBound:SpatialSupportExpanded', ...
        'Upper Bound 在 Candidate lashProtection support 外增加了保护。');
end

upperBoundBeautyMasks = candidateBeautyMasks;
upperBoundBeautyMasks.textureProtectionMask = upperBoundTextureProtectionMask;
if isfield(upperBoundBeautyMasks, 'protectionMask')
    upperBoundBeautyMasks.protectionMask = max(cat(3, ...
        upperBoundTextureProtectionMask, ...
        double(upperBoundBeautyMasks.structureProtectionMask), ...
        double(upperBoundBeautyMasks.hardProtectionMask)), [], 3);
end
validateUpperBoundIsolation(candidateBeautyMasks, upperBoundBeautyMasks, ...
    candidateSupport, options.formulaTolerance);

% 只重跑现有 Smoothing / Repair / compose。Base、tone、whitening 由
% Issue 08.4 的同次 Baseline compose 诊断重建并冻结。
[upperBoundSmoothedFrequency, upperBoundSmoothingDiagnostics] = ...
    beauty.smoothSkinTexture(frequency, upperBoundBeautyMasks, ...
    inputParams.smoothingStrength, blemishMap);
[upperBoundRepairedFrequency, upperBoundRepairDiagnostics] = ...
    beauty.repairSkinBlemishes(upperBoundSmoothedFrequency, ...
    upperBoundBeautyMasks, blemishMap, inputParams.smoothingStrength);
processing = buildFrozenProcessing( ...
    continuityDiagnostics.baselineComposeDiagnostics);
[reconstructedBaseline, reconstructedBaselineComposeDiagnostics] = ...
    beauty.composeBeautyResult(inputImage, frequency, ...
    continuityDiagnostics.repairedFrequency, baselineBeautyMasks, ...
    inputParams.whiteningStrength, processing);
[reconstructedCandidate, reconstructedCandidateComposeDiagnostics] = ...
    beauty.composeBeautyResult(inputImage, frequency, ...
    continuityDiagnostics.candidateRepairedFrequency, candidateBeautyMasks, ...
    inputParams.whiteningStrength, processing);
[upperBoundOutput, upperBoundComposeDiagnostics] = ...
    beauty.composeBeautyResult(inputImage, frequency, ...
    upperBoundRepairedFrequency, upperBoundBeautyMasks, ...
    inputParams.whiteningStrength, processing);

baselineOutput = continuityDiagnostics.baselineComposed;
candidateOutput = continuityDiagnostics.candidateOutput;
baselineComposeMaxRgbDifference = max(abs(double(reconstructedBaseline(:)) - ...
    double(baselineOutput(:))));
candidateComposeMaxRgbDifference = max(abs(double(reconstructedCandidate(:)) - ...
    double(candidateOutput(:))));
if baselineComposeMaxRgbDifference > options.reconstructionTolerance || ...
        candidateComposeMaxRgbDifference > options.reconstructionTolerance
    error('diagnoseLashProtectionSufficiencyUpperBound:FrozenComposeMismatch', ...
        '冻结 Base/tone/whitening 重建不一致：Baseline %.17g，Candidate %.17g。', ...
        baselineComposeMaxRgbDifference, candidateComposeMaxRgbDifference);
end

originalLuminance = rgb2ycbcr(im2double(inputImage));
originalLuminance = originalLuminance(:, :, 1);
validateArray(originalLuminance, imageSize, 'originalLuminance');

baselineSmoothedFrequency = continuityDiagnostics.smoothedFrequency;
candidateSmoothedFrequency = continuityDiagnostics.candidateSmoothedFrequency;
baselineRepairedFrequency = continuityDiagnostics.repairedFrequency;
candidateRepairedFrequency = continuityDiagnostics.candidateRepairedFrequency;
baselineRepairFineDelta = double(baselineRepairedFrequency.fine) - ...
    double(baselineSmoothedFrequency.fine);
candidateRepairFineDelta = double(candidateRepairedFrequency.fine) - ...
    double(candidateSmoothedFrequency.fine);
upperBoundRepairFineDelta = double(upperBoundRepairedFrequency.fine) - ...
    double(upperBoundSmoothedFrequency.fine);
baselineRepairMidDelta = double(baselineRepairedFrequency.mid) - ...
    double(baselineSmoothedFrequency.mid);
candidateRepairMidDelta = double(candidateRepairedFrequency.mid) - ...
    double(candidateSmoothedFrequency.mid);
upperBoundRepairMidDelta = double(upperBoundRepairedFrequency.mid) - ...
    double(upperBoundSmoothedFrequency.mid);

baselineRgbDistance = max(abs(double(baselineOutput) - ...
    double(inputImage)), [], 3);
candidateRgbDistance = max(abs(double(candidateOutput) - ...
    double(inputImage)), [], 3);
upperBoundRgbDistance = max(abs(double(upperBoundOutput) - ...
    double(inputImage)), [], 3);
baselineLuminanceDistance = abs(double( ...
    continuityDiagnostics.baselineComposeDiagnostics.outputLuminance) - ...
    double(originalLuminance));
candidateLuminanceDistance = abs(double( ...
    continuityDiagnostics.candidateComposeDiagnostics.outputLuminance) - ...
    double(originalLuminance));
upperBoundLuminanceDistance = abs(double( ...
    upperBoundComposeDiagnostics.outputLuminance) - ...
    double(originalLuminance));

browEyeMask = makeRoiMask(options.browEyeRoi, imageSize);
manualOutsideBrowEyeMask = browEyeMask & ~manualLashMask;
candidateUpperRgbChange = max(abs(double(upperBoundOutput) - ...
    double(candidateOutput)), [], 3);
candidateUpperLuminanceChange = abs(double( ...
    upperBoundComposeDiagnostics.outputLuminance) - ...
    double(continuityDiagnostics.candidateComposeDiagnostics.outputLuminance));

baselineHardMask = double(baselineBeautyMasks.hardProtectionMask);
candidateHardMask = double(candidateBeautyMasks.hardProtectionMask);
upperBoundHardMask = double(upperBoundBeautyMasks.hardProtectionMask);
hardProtectionMaskChangedPixels = struct( ...
    'baselineToCandidate', nnz(baselineHardMask ~= candidateHardMask), ...
    'baselineToUpperBound', nnz(baselineHardMask ~= upperBoundHardMask), ...
    'candidateToUpperBound', nnz(candidateHardMask ~= upperBoundHardMask));

baselineLashCore = logical(baselineTextureDiagnostics.lashCore);
candidateLashCore = logical(candidateTextureDiagnostics.lashCore);
upperBoundLashCore = candidateLashCore;
lashCoreChangedPixels = struct( ...
    'baselineToCandidate', nnz(baselineLashCore ~= candidateLashCore), ...
    'baselineToUpperBound', nnz(baselineLashCore ~= upperBoundLashCore), ...
    'candidateToUpperBound', nnz(candidateLashCore ~= upperBoundLashCore));

hardRegion = baselineHardMask >= .999;
baselineHardChanged = max(abs(double(baselineOutput) - ...
    double(inputImage)), [], 3) > 0;
candidateHardChanged = max(abs(double(candidateOutput) - ...
    double(inputImage)), [], 3) > 0;
upperBoundHardChanged = max(abs(double(upperBoundOutput) - ...
    double(inputImage)), [], 3) > 0;
hardProtectedFinalRgbChangedCount = struct( ...
    'baseline', nnz(baselineHardChanged(hardRegion)), ...
    'candidate', nnz(candidateHardChanged(hardRegion)), ...
    'upperBound', nnz(upperBoundHardChanged(hardRegion)));

metrics = makeMetrics(manualLashMask, manualOutsideBrowEyeMask, ...
    candidateLashProtection, upperBoundLashProtection, ...
    candidateSupport, baselineRepairFineDelta, candidateRepairFineDelta, ...
    upperBoundRepairFineDelta, baselineRepairMidDelta, ...
    candidateRepairMidDelta, upperBoundRepairMidDelta, ...
    baselineRgbDistance, candidateRgbDistance, upperBoundRgbDistance, ...
    baselineLuminanceDistance, candidateLuminanceDistance, ...
    upperBoundLuminanceDistance, candidateUpperRgbChange, ...
    candidateUpperLuminanceChange, hardProtectionMaskChangedPixels, ...
    lashCoreChangedPixels, hardProtectedFinalRgbChangedCount, ...
    options.nonzeroTolerance);
metrics.candidateUpperTextureChangedPixels = nnz( ...
    abs(upperBoundTextureProtectionMask - candidateTextureProtectionMask) > ...
    options.formulaTolerance);
metrics.candidateUpperTextureChangedOutsideCandidateSupport = nnz( ...
    candidateIncreaseOutsideSupport);
metrics.upperBoundLashStrengthRaisedPixels = nnz( ...
    abs(upperBoundLashProtection - candidateLashProtection) > ...
    options.formulaTolerance);
metrics.upperBoundLashStrengthIncreaseTotal = sum( ...
    upperBoundLashProtection(:) - candidateLashProtection(:));
metrics.upperBoundLashStrengthIncreaseInsideManual = makeStats( ...
    (upperBoundLashProtection(manualLashMask) - ...
    candidateLashProtection(manualLashMask)), options.nonzeroTolerance);
metrics.numericAssessment = assessNumericEvidence(metrics, ...
    supportChangedPixels, options.formulaTolerance);

paths = writeArtifacts(outputFolder, inputImage, manualLashMask, ...
    baselineOutput, candidateOutput, upperBoundOutput, ...
    candidateLashProtection, upperBoundLashProtection, candidateSupport, ...
    baselineRepairFineDelta, candidateRepairFineDelta, ...
    upperBoundRepairFineDelta, baselineRepairMidDelta, ...
    candidateRepairMidDelta, upperBoundRepairMidDelta, options.lashRoi);
paths.csv = fullfile(outputFolder, ...
    'lash_protection_sufficiency_upper_bound_metrics.csv');
writeMetricsCsv(paths.csv, metrics, metrics.numericAssessment, ...
    supportChangedPixels, hardProtectionMaskChangedPixels, ...
    lashCoreChangedPixels, hardProtectedFinalRgbChangedCount);
paths.data = fullfile(outputFolder, ...
    'lash_protection_sufficiency_upper_bound_diagnostic.mat');

summary = struct( ...
    'completed', true, ...
    'issue', '08.5', ...
    'case', 'requiresVisualReview', ...
    'caseAssessment', metrics.numericAssessment, ...
    'contract', continuitySummary.contract, ...
    'imagePath', imagePath, ...
    'inputSize', size(inputImage), ...
    'faceBox', double(options.faceBox), ...
    'browEye', double(options.browEyeRoi), ...
    'lashRoi', double(options.lashRoi), ...
    'parameters', inputParams, ...
    'baselinePath', options.baselinePath, ...
    'manualLashMaskId', annotation.annotationId, ...
    'manualLashMaskIndependent', annotation.diagnosticsIndependent, ...
    'manualLashMaskFixed', annotation.fixedAfterAnnotation, ...
    'manualLashMaskPixels', nnz(manualLashMask), ...
    'runtimeCacheReused', continuitySummary.runtimeCacheReused, ...
    'sameMaskRun', true, ...
    'baseToneWhiteningFrozen', true, ...
    'upperBoundOnlyExistingCandidateSupport', true, ...
    'candidateSupportPixels', nnz(candidateSupport), ...
    'upperBoundSupportPixels', nnz(upperBoundSupport), ...
    'supportChangedPixels', supportChangedPixels, ...
    'baselineComposeMaxRgbDifference', baselineComposeMaxRgbDifference, ...
    'candidateComposeMaxRgbDifference', candidateComposeMaxRgbDifference, ...
    'candidateUpperTextureChangedOutsideCandidateSupport', ...
    metrics.candidateUpperTextureChangedOutsideCandidateSupport, ...
    'hardProtectionMaskChangedPixels', hardProtectionMaskChangedPixels, ...
    'hardProtectedFinalRgbChangedCount', hardProtectedFinalRgbChangedCount, ...
    'lashCoreChangedPixels', lashCoreChangedPixels, ...
    'metrics', metrics, ...
    'paths', paths);

diagnosticData = struct( ...
    'summary', summary, ...
    'inputImage', inputImage, ...
    'annotation', annotation, ...
    'manualLashMask', manualLashMask, ...
    'browEyeMask', browEyeMask, ...
    'manualOutsideBrowEyeMask', manualOutsideBrowEyeMask, ...
    'frequency', frequency, ...
    'blemishMap', blemishMap, ...
    'baselineBeautyMasks', baselineBeautyMasks, ...
    'candidateBeautyMasks', candidateBeautyMasks, ...
    'upperBoundBeautyMasks', upperBoundBeautyMasks, ...
    'baselineTextureDiagnostics', baselineTextureDiagnostics, ...
    'candidateTextureDiagnostics', candidateTextureDiagnostics, ...
    'upperBoundTextureDiagnostics', makeUpperTextureDiagnostics( ...
        baselineTextureDiagnostics, upperBoundEyeDetailProtection, ...
        upperBoundLashProtection), ...
    'baselineLashProtection', baselineLashProtection, ...
    'candidateLashProtection', candidateLashProtection, ...
    'upperBoundLashProtection', upperBoundLashProtection, ...
    'candidateSupport', candidateSupport, ...
    'upperBoundSupport', upperBoundSupport, ...
    'baselineSmoothedFrequency', baselineSmoothedFrequency, ...
    'candidateSmoothedFrequency', candidateSmoothedFrequency, ...
    'upperBoundSmoothedFrequency', upperBoundSmoothedFrequency, ...
    'baselineRepairedFrequency', baselineRepairedFrequency, ...
    'candidateRepairedFrequency', candidateRepairedFrequency, ...
    'upperBoundRepairedFrequency', upperBoundRepairedFrequency, ...
    'upperBoundSmoothingDiagnostics', upperBoundSmoothingDiagnostics, ...
    'upperBoundRepairDiagnostics', upperBoundRepairDiagnostics, ...
    'baselineOutput', baselineOutput, ...
    'candidateOutput', candidateOutput, ...
    'upperBoundOutput', upperBoundOutput, ...
    'baselineComposeDiagnostics', continuityDiagnostics.baselineComposeDiagnostics, ...
    'candidateComposeDiagnostics', continuityDiagnostics.candidateComposeDiagnostics, ...
    'upperBoundComposeDiagnostics', upperBoundComposeDiagnostics, ...
    'reconstructedBaselineComposeDiagnostics', reconstructedBaselineComposeDiagnostics, ...
    'reconstructedCandidateComposeDiagnostics', reconstructedCandidateComposeDiagnostics, ...
    'originalLuminance', originalLuminance, ...
    'baselineRepairFineDelta', baselineRepairFineDelta, ...
    'candidateRepairFineDelta', candidateRepairFineDelta, ...
    'upperBoundRepairFineDelta', upperBoundRepairFineDelta, ...
    'baselineRepairMidDelta', baselineRepairMidDelta, ...
    'candidateRepairMidDelta', candidateRepairMidDelta, ...
    'upperBoundRepairMidDelta', upperBoundRepairMidDelta, ...
    'candidateUpperRgbChange', candidateUpperRgbChange, ...
    'candidateUpperLuminanceChange', candidateUpperLuminanceChange, ...
    'metrics', metrics);
save(paths.data, 'diagnosticData', '-v7.3');
summary.paths = paths;
diagnosticData.summary = summary;
diagnostics = diagnosticData;

fprintf('Issue 08.5 睫毛 Protection Sufficiency Upper Bound 产物：%s\n', ...
    outputFolder);
fprintf('Candidate / Upper Bound support：%d / %d；changed：%d\n', ...
    nnz(candidateSupport), nnz(upperBoundSupport), supportChangedPixels);
fprintf('真实睫毛 lashProtection 均值 Candidate -> Upper：%.17g -> %.17g\n', ...
    metrics.candidateLashProtection.mean, metrics.upperBoundLashProtection.mean);
fprintf('真实睫毛 Repair Fine 绝对作用量：%.17g -> %.17g -> %.17g\n', ...
    metrics.baselineRepairFineAbsAction.sum, ...
    metrics.candidateRepairFineAbsAction.sum, ...
    metrics.upperBoundRepairFineAbsAction.sum);
fprintf('真实睫毛 Repair Mid 绝对作用量：%.17g -> %.17g -> %.17g\n', ...
    metrics.baselineRepairMidAbsAction.sum, ...
    metrics.candidateRepairMidAbsAction.sum, ...
    metrics.upperBoundRepairMidAbsAction.sum);
fprintf('真实睫毛最终 RGB 到原图均值：%.17g -> %.17g -> %.17g\n', ...
    metrics.baselineFinalRgbDistanceToOriginal.mean, ...
    metrics.candidateFinalRgbDistanceToOriginal.mean, ...
    metrics.upperBoundFinalRgbDistanceToOriginal.mean);
fprintf('真实睫毛最终 luminance 到原图均值：%.17g -> %.17g -> %.17g\n', ...
    metrics.baselineFinalLuminanceDistanceToOriginal.mean, ...
    metrics.candidateFinalLuminanceDistanceToOriginal.mean, ...
    metrics.upperBoundFinalLuminanceDistanceToOriginal.mean);
fprintf('hard mask changed B->C/C->U/B->U：%d / %d / %d；lashCore B->C/C->U/B->U：%d / %d / %d\n', ...
    hardProtectionMaskChangedPixels.baselineToCandidate, ...
    hardProtectionMaskChangedPixels.candidateToUpperBound, ...
    hardProtectionMaskChangedPixels.baselineToUpperBound, ...
    lashCoreChangedPixels.baselineToCandidate, ...
    lashCoreChangedPixels.candidateToUpperBound, ...
    lashCoreChangedPixels.baselineToUpperBound);
fprintf('数值证据：%s；最终 Case 需要人工核对四列主图。\n', ...
    metrics.numericAssessment.case);
end

function options = normalizeOptions(options, projectRoot)
if nargin < 1 || isempty(options)
    options = struct();
end
if ~isstruct(options) || ~isscalar(options)
    error('diagnoseLashProtectionSufficiencyUpperBound:InvalidOptions', ...
        'options 必须是标量结构。');
end
fixedFields = { ...
    'faceBox', [95, 79, 286, 372]; ...
    'browEyeRoi', [165, 205, 150, 100]; ...
    'lashRoi', [102, 248, 177, 48]};
for index = 1:size(fixedFields, 1)
    name = fixedFields{index, 1};
    defaultValue = fixedFields{index, 2};
    if ~isfield(options, name) || isempty(options.(name))
        options.(name) = defaultValue;
    end
    if ~isequal(double(options.(name)), double(defaultValue))
        error('diagnoseLashProtectionSufficiencyUpperBound:NonFixedFixture', ...
            '%s 必须复用 Issue 08.5 固定值。', name);
    end
end
options.faceBox = double(options.faceBox);
options.browEyeRoi = double(options.browEyeRoi);
options.lashRoi = double(options.lashRoi);
if ~isfield(options, 'smoothingStrength') || isempty(options.smoothingStrength)
    options.smoothingStrength = 100;
end
if ~isfield(options, 'whiteningStrength') || isempty(options.whiteningStrength)
    options.whiteningStrength = 15;
end
if ~isValidStrength(options.smoothingStrength) || ...
        ~isValidStrength(options.whiteningStrength)
    error('diagnoseLashProtectionSufficiencyUpperBound:InvalidStrength', ...
        '强度必须是 0 到 100 的有限数值标量。');
end
if ~isfield(options, 'productionRoot') || isempty(options.productionRoot)
    options.productionRoot = projectRoot;
end
options.productionRoot = normalizeText(options.productionRoot, ...
    'productionRoot');
if ~isfield(options, 'baselinePath') || isempty(options.baselinePath)
    options.baselinePath = ...
        'C:\Users\JJiio\AppData\Local\Temp\image_beauty_issue02_probe\77_v32_probe.mat';
end
options.baselinePath = normalizeText(options.baselinePath, 'baselinePath');
if ~isfield(options, 'formulaTolerance') || isempty(options.formulaTolerance)
    options.formulaTolerance = 1e-12;
end
if ~isfield(options, 'reconstructionTolerance') || ...
        isempty(options.reconstructionTolerance)
    options.reconstructionTolerance = 1e-12;
end
if ~isfield(options, 'nonzeroTolerance') || isempty(options.nonzeroTolerance)
    options.nonzeroTolerance = 1e-12;
end
if ~isscalar(options.formulaTolerance) || ...
        ~isfinite(options.formulaTolerance) || options.formulaTolerance <= 0 || ...
        ~isscalar(options.reconstructionTolerance) || ...
        ~isfinite(options.reconstructionTolerance) || ...
        options.reconstructionTolerance <= 0 || ...
        ~isscalar(options.nonzeroTolerance) || ...
        ~isfinite(options.nonzeroTolerance) || options.nonzeroTolerance <= 0
    error('diagnoseLashProtectionSufficiencyUpperBound:InvalidTolerance', ...
        '公式、重建和非零容差必须是正的有限标量。');
end
options.formulaTolerance = double(options.formulaTolerance);
options.reconstructionTolerance = double(options.reconstructionTolerance);
options.nonzeroTolerance = double(options.nonzeroTolerance);
end

function root = resolveProductionRoot(root)
if ~isfolder(root) || ~isfolder(fullfile(root, 'src'))
    error('diagnoseLashProtectionSufficiencyUpperBound:InvalidProductionRoot', ...
        '生产算法根目录或 src 目录不存在：%s。', root);
end
end

function validateCommonFixtureShape(inputImage, options)
if ~isequal(size(inputImage), [450, 512, 3]) || ...
        ~isequal(options.faceBox, [95, 79, 286, 372]) || ...
        ~isequal(options.browEyeRoi, [165, 205, 150, 100]) || ...
        ~isequal(options.lashRoi, [102, 248, 177, 48])
    error('diagnoseLashProtectionSufficiencyUpperBound:UnexpectedFixture', ...
        'Issue 08.5 必须复用固定 77 图像尺寸和坐标。');
end
end

function validateCommonFixture(continuitySummary, annotation, inputImage, options)
validateCommonFixtureShape(inputImage, options);
if ~strcmp(annotation.annotationId, '77-manual-lash-v1') || ...
        ~strcmp(continuitySummary.manualLashMaskId, '77-manual-lash-v1')
    error('diagnoseLashProtectionSufficiencyUpperBound:UnexpectedFixture', ...
        'Issue 08.5 必须复用固定 77 人工真值。');
end
end

function image = readInputImage(imagePath)
if ~isfile(imagePath)
    error('diagnoseLashProtectionSufficiencyUpperBound:MissingImage', ...
        '输入图像不存在：%s。', imagePath);
end
image = imread(imagePath);
if ~isa(image, 'uint8') || ~isreal(image) || ndims(image) ~= 3 || ...
        size(image, 3) ~= 3
    error('diagnoseLashProtectionSufficiencyUpperBound:InvalidImage', ...
        '输入图像必须是 uint8 三通道 RGB 图像。');
end
end

function validateUpperBoundIsolation(candidateMasks, upperMasks, support, tolerance)
unchangedNames = {'structureProtectionMask', 'hardProtectionMask', ...
    'whiteningProtectionMask', 'chromaProtectionMask', 'toneProtectionMask', ...
    'strengthMap', 'faceStrengthMap', 'nonFaceStrengthMap', 'skinMask', ...
    'faceSkinMask', 'nonFaceSkinMask', 'noseMask'};
for index = 1:numel(unchangedNames)
    name = unchangedNames{index};
    if isfield(candidateMasks, name) && isfield(upperMasks, name)
        if max(abs(double(candidateMasks.(name)(:)) - ...
                double(upperMasks.(name)(:)))) > tolerance
            error('diagnoseLashProtectionSufficiencyUpperBound:SingleFactorViolation', ...
                'Upper Bound 意外修改了 %s。', name);
        end
    end
end
candidateTexture = double(candidateMasks.textureProtectionMask);
upperTexture = double(upperMasks.textureProtectionMask);
changedOutside = abs(upperTexture - candidateTexture) > tolerance & ~support;
if any(changedOutside(:))
    error('diagnoseLashProtectionSufficiencyUpperBound:SingleFactorViolation', ...
        'Upper Bound 的最终 textureProtectionMask 在 lash support 外发生变化。');
end
if any(upperTexture(:) < -tolerance) || any(upperTexture(:) > 1 + tolerance)
    error('diagnoseLashProtectionSufficiencyUpperBound:InvalidUpperBoundMask', ...
        'Upper Bound textureProtectionMask 不在 [0,1]。');
end
end

