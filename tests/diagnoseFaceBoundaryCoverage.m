function value = meanOn(data, mask)
values = double(data(mask));
if isempty(values)
    value = NaN;
else
    value = mean(values);
end
end

function value = medianOn(data, mask)
values = double(data(mask));
if isempty(values)
    value = NaN;
else
    value = median(values);
end
end

function value = percentileOn(data, mask, fraction)
values = sort(double(data(mask)));
if isempty(values)
    value = NaN;
    return;
end
position = 1 + fraction * (numel(values) - 1);
lower = floor(position);
upper = ceil(position);
if lower == upper
    value = values(lower);
else
    weight = position - lower;
    value = (1 - weight) * values(lower) + weight * values(upper);
end
end

function value = fractionOf(condition, mask)
count = nnz(mask);
if count == 0
    value = NaN;
else
    value = nnz(condition & mask) / count;
end
end

function value = fractionWithDenominator(numerator, denominator)
if denominator == 0
    value = NaN;
else
    value = double(numerator) / double(denominator);
end
end

function value = maxOn(data, mask)
values = double(data(mask));
if isempty(values)
    value = NaN;
else
    value = max(values);
end
end

function roi = roiMask(box, imageSize)
roi = false(imageSize(1), imageSize(2));
x1 = box(1);
y1 = box(2);
x2 = min(imageSize(2), x1 + box(3) - 1);
y2 = min(imageSize(1), y1 + box(4) - 1);
roi(y1:y2, x1:x2) = true;
end

function box = validateRoi(box, name)
if ~isnumeric(box) || ~isreal(box) || ~isequal(size(box), [1, 4]) || ...
        any(~isfinite(box)) || any(box(1:2) < 1) || ...
        any(box(3:4) < 1)
    error('diagnoseFaceBoundaryCoverage:InvalidRoi', ...
        '%s 必须是正整数 [x y width height]。', name);
end
box = round(double(box));
end

function box = validateRoiBounds(box, imageSize, name)
if box(1) + box(3) - 1 > imageSize(2) || ...
        box(2) + box(4) - 1 > imageSize(1)
    error('diagnoseFaceBoundaryCoverage:InvalidRoi', ...
        '%s 超出输入图像范围。', name);
end
end

function box = scaleRoi(sourceBox, scale, imageSize)
box = round(double(sourceBox) * scale);
box(1:2) = max(box(1:2), 1);
x2 = min(imageSize(2), box(1) + box(3) - 1);
y2 = min(imageSize(1), box(2) + box(4) - 1);
box(3:4) = max(1, [x2 - box(1) + 1, y2 - box(2) + 1]);
end

function [preview, scale] = makePreview(image)
scale = min(1, 640 / max(size(image, 1), size(image, 2)));
if scale < 1
    preview = imresize(image, scale, 'bilinear');
else
    preview = image;
end
end

function box = scaleFaceBox(box, scale, imageSize)
box = round(double(box) * scale);
box(1) = max(1, min(box(1), imageSize(2)));
box(2) = max(1, min(box(2), imageSize(1)));
x2 = min(imageSize(2), box(1) + box(3) - 1);
y2 = min(imageSize(1), box(2) + box(4) - 1);
box(3:4) = max(1, [x2 - box(1) + 1, y2 - box(2) + 1]);
end

