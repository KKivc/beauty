function value = normalizeText(value, name)
if isstring(value) && isscalar(value)
    value = char(value);
end
if ~ischar(value) || size(value, 1) ~= 1
    error('diagnoseResidualEyelashLoss:InvalidText', ...
        '%s 必须是单行文本。', name);
end
end

function value = validateRoi(value, name)
if ~isnumeric(value) || ~isreal(value) || ~isequal(size(value), [1, 4]) || ...
        any(~isfinite(value)) || any(value ~= round(value)) || ...
        value(1) < 1 || value(2) < 1 || any(value(3:4) <= 0)
    error('diagnoseResidualEyelashLoss:InvalidLashRoi', ...
        '%s 必须是正整数 [x y width height]。', name);
end
value = double(value);
end

function value = validateRoiList(value, name)
if ~isnumeric(value) || ~isreal(value) || size(value, 2) ~= 4 || ...
        isempty(value) || any(~isfinite(value(:))) || ...
        any(value(:) ~= round(value(:))) || any(value(:, 1:2) < 1, 'all') || ...
        any(value(:, 3:4) <= 0, 'all')
    error('diagnoseResidualEyelashLoss:InvalidLashRoi', ...
        '%s 必须是一个或多个正整数 [x y width height]。', name);
end
value = double(value);
end

function validateRoiBounds(roi, imageSize, name)
if roi(1) + roi(3) - 1 > imageSize(2) || ...
        roi(2) + roi(4) - 1 > imageSize(1)
    error('diagnoseResidualEyelashLoss:InvalidLashRoi', ...
        '%s 超出输入图像范围。', name);
end
end

function bounds = boundsOfRoiList(rois)
x1 = min(rois(:, 1));
y1 = min(rois(:, 2));
x2 = max(rois(:, 1) + rois(:, 3) - 1);
y2 = max(rois(:, 2) + rois(:, 4) - 1);
bounds = [x1, y1, x2 - x1 + 1, y2 - y1 + 1];
end

function mask = makeRoiMask(roi, imageSize)
mask = false(imageSize(1), imageSize(2));
x1 = roi(1);
y1 = roi(2);
x2 = roi(1) + roi(3) - 1;
y2 = roi(2) + roi(4) - 1;
mask(y1:y2, x1:x2) = true;
end

function [meanAbs, maximum, nonzeroFraction] = summarizeDelta(delta, mask, tolerance)
values = abs(double(delta(mask)));
if isempty(values)
    meanAbs = NaN;
    maximum = NaN;
    nonzeroFraction = NaN;
else
    meanAbs = mean(values);
    maximum = max(values);
    nonzeroFraction = nnz(values > tolerance) / numel(values);
end
end

function value = meanOn(data, mask)
values = double(data(mask));
if isempty(values)
    value = NaN;
else
    value = mean(values);
end
end

function value = maxOn(data, mask)
values = double(data(mask));
if isempty(values)
    value = NaN;
else
    value = max(values);
end
end

function value = fractionOfAny(data, mask)
values = logical(data(mask));
if isempty(values)
    value = NaN;
else
    value = nnz(values) / numel(values);
end
end

function value = safeRatio(numerator, denominator)
if denominator <= eps
    if numerator <= eps
        value = 0;
    else
        value = Inf;
    end
else
    value = numerator / denominator;
end
end

function image = cropImage(image, box)
x1 = box(1);
y1 = box(2);
x2 = min(size(image, 2), box(1) + box(3) - 1);
y2 = min(size(image, 1), box(2) + box(4) - 1);
if ismatrix(image)
    image = image(y1:y2, x1:x2);
else
    image = image(y1:y2, x1:x2, :);
end
end

function writeMaskCrop(mask, box, path)
writePng(uint8(min(max(round(255 * double(cropImage(mask, box))), 0), 255)), ...
    path);
end

function writeDeltaCrop(delta, box, scale, path)
value = abs(double(cropImage(delta, box))) / max(scale, eps);
writePng(uint8(min(max(round(255 * value), 0), 255)), path);
end

function writePng(image, path)
if ~isa(image, 'uint8')
    image = uint8(min(max(round(double(image)), 0), 255));
end
imwrite(image, path);
end

