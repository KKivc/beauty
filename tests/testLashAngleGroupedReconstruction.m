verifyEqual(testCase, diagnostics.candidate087GeometrySeed, expected087);
verifyEqual(testCase, diagnostics.angleGrouped.angleStats.finalUnionPixels, ...
    nnz(expected087));

expectedSoft087 = makeExpectedSoftMask(diagnostics.candidate087GeometrySeed, ...
    summary.softRadius, summary.softPeak);
expectedSoft087(~diagnostics.evidence.eyeNeighborhood) = 0;
expectedSoft087 = min(max(double(expectedSoft087), 0), 1);
verifyEqual(testCase, diagnostics.candidate087LashProtection, expectedSoft087, ...
    'AbsTol', 1e-12);
verifyEqual(testCase, diagnostics.candidate087Support, ...
    diagnostics.candidate087LashProtection > 0);
verifyEqual(testCase, diagnostics.candidate086Support, ...
    diagnostics.candidate086LashProtection > 0);
verifyEqual(testCase, diagnostics.candidate087TextureDiagnostics.lashCore, ...
    diagnostics.baselineTextureDiagnostics.lashCore);
verifyEqual(testCase, diagnostics.candidate087BeautyMasks.hardProtectionMask, ...
    diagnostics.baselineBeautyMasks.hardProtectionMask, 'AbsTol', 0);
verifyEqual(testCase, diagnostics.candidate087BeautyMasks.structureProtectionMask, ...
    diagnostics.baselineBeautyMasks.structureProtectionMask, 'AbsTol', 0);

for group = {'baseline', 'candidate084', 'candidate086', 'candidate087'}
    metrics = summary.metrics.(group{1});
    verifyEqual(testCase, metrics.truePositivePixels + ...
        metrics.falseNegativePixels, summary.manualLashMaskPixels);
