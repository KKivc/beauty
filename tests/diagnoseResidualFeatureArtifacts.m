function [output, details] = runPipelineWithMasks(inputImage, frequency, ...
        beautyMasks, blemishMap, params)
[smoothed, smoothingDiagnostics] = beauty.smoothSkinTexture( ...
    frequency, beautyMasks, params.smoothingStrength, blemishMap);
[repaired, repairDiagnostics] = beauty.repairSkinBlemishes( ...
    smoothed, beautyMasks, blemishMap, params.smoothingStrength);
[base, baseDiagnostics] = beauty.evenSkinLuminance( ...
    frequency, beautyMasks, params.smoothingStrength);
[skinTone, skinToneDiagnostics] = beauty.normalizeSkinTone( ...
    inputImage, frequency, beautyMasks, blemishMap, ...
    params.smoothingStrength);
[whitening, whiteningDiagnostics] = beauty.applySkinWhitening( ...
    inputImage, frequency, beautyMasks, params.whiteningStrength);
processing = struct( ...
    'baseLuminance', base, ...
    'skinTone', skinTone, ...
    'whitening', whitening);
[output, composeDiagnostics] = beauty.composeBeautyResult( ...
    inputImage, frequency, repaired, beautyMasks, ...
    params.whiteningStrength, processing);
details = struct( ...
    'smoothing', smoothingDiagnostics, ...
    'repair', repairDiagnostics, ...
    'base', baseDiagnostics, ...
    'skinTone', skinToneDiagnostics, ...
    'whitening', whiteningDiagnostics, ...
    'compose', composeDiagnostics);
end

