components = bwconncomp(mask, 8);
if components.NumObjects == 0
    sizes = zeros(0, 1);
    largest = 0;
    longestSpan = 0;
else
    sizes = cellfun(@numel, components.PixelIdxList).';
    largest = max(sizes);
    [rows, columns] = find(mask);
    longestSpan = max(max(rows) - min(rows) + 1, ...
        max(columns) - min(columns) + 1);
end
stats = struct( ...
    'componentCount', components.NumObjects, ...
    'componentSizes', sizes, ...
    'largestComponentPixels', largest, ...
    'longestBoundingSpan', longestSpan);
end

function assessment = assessNumericGeometry(metrics, tolerance)
p86 = metrics.candidate086.precision;
p87 = metrics.candidate087.precision;
r86 = metrics.candidate086.recall;
r87 = metrics.candidate087.recall;
precisionImproved = p87 > p86 + tolerance;
recallNotLower = r87 >= r86 - tolerance;
fpPixelsReduced = metrics.candidate087.falsePositivePixels < ...
    metrics.candidate086.falsePositivePixels;
fpLargestReduced = metrics.candidate087.falsePositiveComponents ...
    .largestComponentPixels < ...
    metrics.candidate086.falsePositiveComponents.largestComponentPixels;
if precisionImproved && recallNotLower && (fpPixelsReduced || fpLargestReduced)
    caseName = 'numericGeometrySupportsCandidate';
else
    caseName = 'numericGeometryDoesNotSupportCandidate';
end
assessment = struct( ...
    'case', caseName, ...
    'requiresVisualReview', true, ...
    'precisionImproved', precisionImproved, ...
    'recallNotLower', recallNotLower, ...
    'falsePositivePixelsReduced', fpPixelsReduced, ...
    'falsePositiveLargestComponentReduced', fpLargestReduced, ...
    'baselineComparison', '08.6 -> 08.7', ...
    'basis', ['Precision/Recall 和 FP 连续分量仅作离线证据；', ...
    '最终 Case 必须结合同尺度主图人工确认。']);
end

function assessment = assessRepair(metrics, tolerance)
fine086 = metrics.candidate086RepairFineAbsAction.sum;
fine087 = metrics.candidate087RepairFineAbsAction.sum;
mid086 = metrics.candidate086RepairMidAbsAction.sum;
mid087 = metrics.candidate087RepairMidAbsAction.sum;
assessment = struct( ...
    'fineNotWorseThan086', fine087 <= fine086 + tolerance, ...
    'midNotWorseThan086', mid087 <= mid086 + tolerance, ...
    'fineReductionFrom086', fine086 - fine087, ...
    'midReductionFrom086', mid086 - mid087, ...
    'requiresVisualReview', true);
end

function value = safeRatio(numerator, denominator)
if denominator == 0
    value = NaN;
else
    value = numerator / denominator;
end
end

