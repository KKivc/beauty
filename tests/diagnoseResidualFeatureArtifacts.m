function safety = buildSafetyMasks(context, definitions, beautyMasks)
imageSize = size(beautyMasks.skinMask);
safety = struct();
hairDefinition = findDefinition(definitions, 'hair');
backgroundDefinition = findDefinition(definitions, 'background');
if isempty(hairDefinition)
    regions = readSemanticStruct(context, 'regions', imageSize);
    confidence = readSemanticStruct(context, ...
        'regionConfidence', imageSize);
    safety.hair = semanticUnion(regions, confidence, {'hair'}) >= .45;
else
    safety.hair = regionMask(hairDefinition.roi, imageSize);
end
if isempty(backgroundDefinition)
    regions = readSemanticStruct(context, 'regions', imageSize);
    confidence = readSemanticStruct(context, ...
        'regionConfidence', imageSize);
    safety.background = semanticUnion(regions, confidence, ...
        {'background'}) >= .45;
else
    safety.background = regionMask(backgroundDefinition.roi, imageSize);
end
safety.hard = readMask(beautyMasks, 'hardProtectionMask', imageSize) >= .999;
end

function definition = findDefinition(definitions, name)
definition = [];
for index = 1:numel(definitions)
    if strcmp(definitions(index).name, name)
        definition = definitions(index);
        return;
    end
end
end

function values = structureSourceFractions(dominant, roi)
values = zeros(1, 4);
valid = roi & dominant > 0;
if ~any(valid(:))
    values(:) = NaN;
    return;
end
for index = 1:4
    values(index) = fractionOf(dominant == index, valid);
end
end

function name = dominantSourceName(fractions, names)
if all(isnan(fractions))
    name = '未适用';
    return;
end
maximum = max(fractions, [], 'omitnan');
if nnz(abs(fractions - maximum) <= 1e-12) ~= 1
    name = '并列';
else
    name = names{find(abs(fractions - maximum) <= 1e-12, 1)};
end
end

function semantics = readSemanticStruct(context, fieldName, imageSize)
names = faceParsingClassNames();
if ~isstruct(context) || ~isfield(context, fieldName) || ...
        ~isstruct(context.(fieldName)) || ...
        ~isscalar(context.(fieldName))
    error('diagnoseResidualFeatureArtifacts:MissingDiagnosticField', ...
        'Beauty Context 缺少语义字段 %s。', fieldName);
end
source = context.(fieldName);
semantics = struct();
for index = 1:numel(names)
    name = names{index};
    if ~isfield(source, name)
        error('diagnoseResidualFeatureArtifacts:MissingDiagnosticField', ...
            'Beauty Context 的 %s 缺少语义字段 %s。', fieldName, name);
    end
    sourceValue = source.(name);
    if ~isnumeric(sourceValue) || ~isreal(sourceValue) || ...
            ~isequal(size(sourceValue), imageSize) || ...
            any(~isfinite(sourceValue(:)))
        error('diagnoseResidualFeatureArtifacts:InvalidDiagnosticArray', ...
            'Beauty Context 的 %s.%s 尺寸或取值无效。', fieldName, name);
    end
    semantics.(name) = double(sourceValue);
end
end

function confidence = makeUnitConfidence(semantics)
confidence = semantics;
names = fieldnames(semantics);
for index = 1:numel(names)
    confidence.(names{index}) = ones(size(semantics.(names{index})));
end
end

function evidence = semanticUnion(regions, confidence, names)
evidence = zeros(size(regions.(names{1})));
for index = 1:numel(names)
    evidence = max(evidence, min(double(regions.(names{index})), ...
        double(confidence.(names{index}))));
end
evidence = min(max(evidence, 0), 1);
end

function values = readSemanticEvidence(context, names, imageSize)
regions = readSemanticStruct(context, 'regions', imageSize);
confidence = readSemanticStruct(context, ...
    'regionConfidence', imageSize);
values = semanticUnion(regions, confidence, names);
end

function value = readLogicalField(value, name)
if ~isfield(value, name)
    error('diagnoseResidualFeatureArtifacts:MissingDiagnosticField', ...
        '诊断结构缺少逻辑字段 %s。', name);
end
value = logical(value.(name));
if ~isscalar(value)
    value = any(value(:));
end
end

function value = diagnosticMask(diagnostics, name, imageSize)
if ~isstruct(diagnostics) || ~isfield(diagnostics, name)
    error('diagnoseResidualFeatureArtifacts:MissingDiagnosticField', ...
        '诊断结构缺少 Mask 字段 %s。', name);
end
value = diagnostics.(name);
if (~isnumeric(value) && ~islogical(value)) || ~isreal(value) || ...
        ~isequal(size(value), imageSize) || any(~isfinite(value(:)))
    error('diagnoseResidualFeatureArtifacts:InvalidDiagnosticMask', ...
        '诊断字段 %s 的尺寸或取值无效。', name);
end
value = value >= .5;
end

function value = diagnosticArray(diagnostics, name, imageSize)
if ~isstruct(diagnostics) || ~isfield(diagnostics, name)
    error('diagnoseResidualFeatureArtifacts:MissingDiagnosticField', ...
        '诊断结构缺少数组字段 %s。', name);
end
value = readArray(diagnostics.(name), imageSize, name);
end

function value = readArray(value, imageSize, name)
if ~isnumeric(value) || ~isreal(value) || ...
        ~isequal(size(value), imageSize) || any(~isfinite(value(:)))
    error('diagnoseResidualFeatureArtifacts:InvalidDiagnosticArray', ...
        '诊断数组 %s 的尺寸或取值无效。', name);
end
value = double(value);
end

function value = readMask(context, name, imageSize)
if ~isfield(context, name)
    error('diagnoseResidualFeatureArtifacts:MissingMask', ...
        'Beauty Masks 缺少字段 %s。', name);
end
value = context.(name);
if (~isnumeric(value) && ~islogical(value)) || ~isreal(value) || ...
        ~isequal(size(value), imageSize) || any(~isfinite(value(:))) || ...
        any(value(:) < 0) || any(value(:) > 1)
    error('diagnoseResidualFeatureArtifacts:InvalidMask', ...
        'Beauty Masks 字段 %s 无效。', name);
end
value = double(value);
end

