finalLuminanceValues = abs(double(finalLuminanceDifference(manualMask)));
rgbValues = double(finalRgbDifference(manualMask));
metrics = struct( ...
    'manualLashPixels', nnz(manualMask), ...
    'textureProtection', makeStats(textureValues), ...
    'textureGate', makeStats(gateValues), ...
    'mediumWeightBeforeTextureGate', makeStats(beforeValues), ...
    'mediumWeightAfterTextureGate', makeStats(afterValues), ...
    'mediumWeightAttenuation', makeStats(attenuationValues), ...
    'baselineMidDelta', makeStats(baselineValues), ...
    'baselineMidDeltaAbs', makeStats(abs(baselineValues)), ...
    'noTextureGateMidDelta', makeStats(noTextureValues), ...
    'noTextureGateMidDeltaAbs', makeStats(abs(noTextureValues)), ...
    'midGateEffectAbs', makeStats(midEffectValues), ...
    'finalLuminanceEffectAbs', makeStats(finalLuminanceValues), ...
    'finalRgbEffectAbs', makeStats(rgbValues), ...
    'finalRgbChangedPixels', nnz(rgbValues > 0), ...
    'manualMask', manualMask);
end

function assessment = classifyCase(metrics)
manualProtectionMean = metrics.textureProtection.mean;
baselineAbsMass = metrics.baselineMidDeltaAbs.sum;
if baselineAbsMass > 0
    protectionWeightedByBaselineMid = ...
        sum(double(metrics.textureProtection.values) .* ...
        double(metrics.baselineMidDeltaAbs.values)) / baselineAbsMass;
else
    protectionWeightedByBaselineMid = NaN;
end
finalEffectMass = metrics.finalLuminanceEffectAbs.sum;
midEffectMass = metrics.midGateEffectAbs.sum;

% 不设置新的 0.x 经验阈值：Case C 只在单因素 Mid 变化或最终亮度
% 变化严格为零时成立；A/B 使用人工真值内的连续加权均值相对关系。
if midEffectMass == 0 || finalEffectMass == 0
    caseName = 'C';
    reason = ['取消 textureGate 对固定真实睫毛的 Mid 局部结果没有产生 ', ...
        '可观测的连续最终亮度变化；当前 gate 不是主要控制因素。'];
elseif baselineAbsMass == 0 || ...
        protectionWeightedByBaselineMid < manualProtectionMean
    caseName = 'A';
    reason = ['当前 textureGate 产生了连续 Mid 衰减，取消后固定真实睫毛的 ', ...
        '单因素结果发生变化；Baseline Mid 作用量按 Protection 加权更偏向 ', ...
        '人工真值内相对较弱的保护位置。'];
else
    caseName = 'B';
    reason = ['当前 textureGate 产生了连续 Mid 衰减，但 Baseline Mid 作用量 ', ...
        '按 Protection 加权不低于人工真值均值，残留仍主要位于已被衰减的 ', ...
        '真实睫毛位置；仅补 nonzero coverage 不足以解释残留。'];
end
assessment = struct( ...
    'case', caseName, ...
    'reason', reason, ...
    'classificationBasis', ['固定 manualLashMask 内的连续 Protection、', ...
        'Mid 权重衰减、Mid delta 和最终亮度差；不使用新的 0.x 生产阈值。'], ...
    'requiresVisualReview', true, ...
    'manualTextureProtectionMean', manualProtectionMean, ...
    'baselineMidAbsMass', baselineAbsMass, ...
    'baselineMidProtectionWeightedMean', protectionWeightedByBaselineMid, ...
    'midGateEffectAbsMass', midEffectMass, ...
    'finalLuminanceEffectAbsMass', finalEffectMass, ...
    'finalRgbChangedPixels', metrics.finalRgbChangedPixels);
end

function stats = makeStats(values)
values = double(values(:));
if isempty(values)
    stats = struct('values', values, 'count', 0, 'sum', 0, ...
        'mean', NaN, 'min', NaN, 'max', NaN, 'median', NaN, ...
        'p25', NaN, 'p75', NaN);
    return;
end
stats = struct( ...
    'values', values, ...
    'count', numel(values), ...
    'sum', sum(values), ...
    'mean', mean(values), ...
    'min', min(values), ...
    'max', max(values), ...
    'median', median(values), ...
    'p25', percentileLinear(values, .25), ...
    'p75', percentileLinear(values, .75));
end

function value = percentileLinear(values, fraction)
values = sort(double(values(:)));
if isempty(values)
    value = NaN;
    return;
end
position = 1 + (numel(values) - 1) * fraction;
low = floor(position);
high = ceil(position);
if low == high
    value = values(low);
else
    value = values(low) + (position - low) * (values(high) - values(low));
end
end

