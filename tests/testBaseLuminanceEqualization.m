sourceYcbcr = rgb2ycbcr(im2double(image));
sourceLuminance = sourceYcbcr(:, :, 1);
frequency = struct('sourceLuminance', sourceLuminance, ...
    'base', sourceLuminance, 'mid', zeros(imageSize), ...
    'fine', zeros(imageSize));
