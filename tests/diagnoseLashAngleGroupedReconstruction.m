baselineSupport = baselineLashProtection > 0;
candidate084LashProtection = readDiagnosticArray( ...
    continuityDiagnostics.candidateLashProtection, imageSize, ...
    'candidate084LashProtection');
candidate084Support = candidate084LashProtection > 0;
candidate086Support = candidate086LashProtection > 0;
candidate087Support = candidate087LashProtection > 0;
candidate086TextureDiagnostics = makeCandidateTextureDiagnostics( ...
    baselineTextureDiagnostics, candidate086EyeDetailProtection, ...
    candidate086LashProtection);
candidate087TextureDiagnostics = makeCandidateTextureDiagnostics( ...
    baselineTextureDiagnostics, candidate087EyeDetailProtection, ...
    candidate087LashProtection);
metrics = makeMetrics(manualLashMask, baselineSupport, ...
    candidate084Support, candidate086Support, candidate087Support, ...
    baselineLashProtection, candidate084LashProtection, ...
    candidate086LashProtection, candidate087LashProtection, ...
    baselineRepairFineDelta, candidate084RepairFineDelta, ...
    candidate086RepairFineDelta, candidate087RepairFineDelta, ...
    baselineRepairMidDelta, candidate084RepairMidDelta, ...
    candidate086RepairMidDelta, candidate087RepairMidDelta, ...
    baselineRgbDistance, candidate084RgbDistance, candidate086RgbDistance, ...
    candidate087RgbDistance, baselineLuminanceDistance, ...
    candidate084LuminanceDistance, candidate086LuminanceDistance, ...
    candidate087LuminanceDistance, options.nonzeroTolerance);
metrics.numericGeometryAssessment = assessNumericGeometry(metrics, ...
    options.formulaTolerance);
metrics.repairAssessment = assessRepair(metrics, options.formulaTolerance);
metrics.candidate086HardProtectionMaskChangedPixels = nnz( ...
    double(candidate086BeautyMasks.hardProtectionMask) ~= ...
    double(baselineBeautyMasks.hardProtectionMask));
metrics.hardProtectionMaskChangedPixels = nnz( ...
