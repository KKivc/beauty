function metrics = makeManualMetrics(manualMask, textureProtectionMask, ...
        weights, baselineMidDelta, noTextureGateMidDelta, ...
        finalLuminanceDifference, finalRgbDifference)
textureValues = double(textureProtectionMask(manualMask));
gateValues = double(weights.textureGate(manualMask));
beforeValues = double(weights.mediumWeightBeforeTextureGate(manualMask));
afterValues = double(weights.mediumWeightAfterTextureGate(manualMask));
attenuationValues = double( ...
    weights.mediumWeightAttenuationByTextureGate(manualMask));
baselineValues = double(baselineMidDelta(manualMask));
noTextureValues = double(noTextureGateMidDelta(manualMask));
