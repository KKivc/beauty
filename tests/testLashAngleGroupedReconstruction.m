verifyEqual(testCase, ...
    summary.metrics.candidate087RepairFineAbsAction.sum, ...
    sum(abs(diagnostics.candidate087RepairFineDelta( ...
    diagnostics.manualLashMask))), 'AbsTol', 1e-12);
