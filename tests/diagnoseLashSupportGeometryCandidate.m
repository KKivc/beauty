    'rightEyeEvidence', rightEyeEvidence, ...
    'browEvidence', browEvidence, ...
    'browCore', browCore, ...
    'eyeNeighborhood', allNeighborhood, ...
    'ring', allRing, ...
    'launchMask', allLaunchMask, ...
    'nearEye', allNearEye, ...
    'darkCandidate', allDarkCandidate, ...
    'edgeCandidate', allEdgeCandidate, ...
    'lineSupport', allLineSupport, ...
    'detectorSeed', allDetectorCandidate, ...
