    ~, row.fineRepairEnergyMean, row.fineRepairRetentionRatio, ...
    row.fineRepairRetentionStatus] = energyRetention( ...
    double(frequency.fine), double(baseline.repairResult.fine), analysis);
[
    row.midInputEnergyMean, row.midSmoothingEnergyMean, ...
    row.midSmoothingRetentionRatio, row.midSmoothingRetentionStatus] = ...
