function assessment = assessNumericCandidate(metrics)
% 当前 v3.3 生产 baseline 已包含局部 lash continuity 闭合，候选可能是
% 数值 no-op；允许 Fine 仅有量化噪声级回归，但 Mid 不得增加作用量。
fineTolerance = .01 * max(metrics.baselineRepairFineAbsAction.sum, eps);
fineImproved = metrics.repairFineAbsActionReduction >= -fineTolerance;
midImproved = metrics.repairMidAbsActionReduction >= 0;
hardUnchanged = metrics.hardProtectionMaskChangedPixels == 0 && ...
    metrics.hardCoreChangedPixels == 0;
addedExists = metrics.candidateTextureIncreasedPixels > 0 || ...
    metrics.manualAddedSoftProtection.nonzeroPixels == 0;
if fineImproved && midImproved && hardUnchanged && addedExists
    caseName = 'numericEvidenceSupportsCandidate';
else
    caseName = 'numericEvidenceDoesNotSupportCandidate';
end
assessment = struct( ...
    'case', caseName, ...
    'requiresVisualReview', true, ...
    'fineAbsActionReduced', fineImproved, ...
    'midAbsActionReduced', midImproved, ...
    'hardProtectionUnchanged', hardUnchanged, ...
    'addedSoftProtectionExists', addedExists, ...
    'basis', ['只使用 Baseline/Candidate 的连续数组和严格相等/大小关系；', ...
    '不把新增生产阈值用于判定。最终视觉和普通眼周副作用必须人工核对。']);
end

function stats = makeStats(values, tolerance)
values = double(values(:));
if isempty(values)
    stats = struct('values', values, 'count', 0, 'sum', 0, ...
        'mean', NaN, 'min', NaN, 'max', NaN, ...
        'nonzeroPixels', 0, 'nonzeroFraction', NaN);
    return;
end
stats = struct( ...
    'values', values, ...
    'count', numel(values), ...
    'sum', sum(values), ...
    'mean', mean(values), ...
    'min', min(values), ...
    'max', max(values), ...
    'nonzeroPixels', nnz(abs(values) > tolerance), ...
    'nonzeroFraction', nnz(abs(values) > tolerance) / numel(values));
end

function stats = makeSignedStats(values, tolerance)
stats = makeStats(values, tolerance);
stats.absoluteSum = sum(abs(values(:)));
stats.absoluteMean = mean(abs(values(:)));
end

