function [summary, diagnostics] = diagnoseLashSupportGeometryCandidate( ...
        imagePath, outputFolder, options)
%DIAGNOSELASHSUPPORTGEOMETRYCANDIDATE 验证 Issue 08.6 唯一几何候选。
%   本入口不修改生产 src。它固定复用 77.png、77-manual-lash-v1、
%   faceBox/browEye/lashRoi、磨皮 100、美白 15 和当前生产链；Baseline
%   与 08.4 Candidate 由既有诊断入口生成，08.6 只替换 lash support
%   geometry，并继续执行同一 Smoothing、Repair 和 compose。
%
%   08.6 的几何候选只复用当前 buildTextureProtectionMask.m 已有的：
%   darkCandidate、edgeCandidate、lineSupport、eyeNeighborhood、当前
%   detector candidate seed、faceScale 派生尺度和当前 featherSoftMask
%   语义。候选使用 evidence 中与既有 detector seed 连通的区域；不使用
%   manualLashMask 生成候选，不新增模型、特征、阈值或绝对像素尺度。
%
%   [summary, diagnostics] = diagnoseLashSupportGeometryCandidate( ...
%       'E:\image_beauty\人脸\人脸\77.png', tempdir, struct( ...
%       'productionRoot', 'E:\image_beauty', ...
%       'baselinePath', ...
%       'C:\Users\JJiio\AppData\Local\Temp\image_beauty_issue02_probe\77_v32_probe.mat'));

projectRoot = fileparts(fileparts(mfilename('fullpath')));
if nargin < 2
    outputFolder = [];
end
if nargin < 3
    options = [];
end
options = normalizeOptions(options, projectRoot);

productionRoot = resolveProductionRoot(options.productionRoot);
addpath(fullfile(productionRoot, 'src'), '-begin');
addpath(fileparts(mfilename('fullpath')), '-begin');

if nargin < 1 || isempty(imagePath)
    error('diagnoseLashSupportGeometryCandidate:MissingImage', ...
        '必须提供固定 77.png 的输入图像路径。');
end
imagePath = normalizeText(imagePath, 'imagePath');
inputImage = readInputImage(imagePath);
imageSize = [size(inputImage, 1), size(inputImage, 2)];
validateFixed77Fixture(inputImage, options);
outputFolder = normalizeOutputFolder(outputFolder);

% 先复用已完成的 08.4 诊断，得到同一次生产基线、08.4 Candidate、
% frequency、blemishMap、其它 Mask 和冻结的 Base/tone/whitening。08.4
% Candidate 的生成路径本身不消费 manualLashMask；其人工真值只用于统计。
stageFolder = tempname;
mkdir(stageFolder);
[continuitySummary, continuityDiagnostics] = ...
    diagnoseLashSoftContinuityCandidate(imagePath, stageFolder, options);
validateContinuityStage(continuitySummary, continuityDiagnostics, imageSize);

manualLashMask = continuityDiagnostics.manualLashMask;
annotation = continuityDiagnostics.annotation;
if ~annotation.diagnosticsIndependent || ~annotation.fixedAfterAnnotation || ...
        ~strcmp(annotation.annotationId, '77-manual-lash-v1')
    error('diagnoseLashSupportGeometryCandidate:InvalidManualTruth', ...
        'manualLashMask 必须是固定、独立的 77-manual-lash-v1。');
end

loaded = loadBaselineContext(options.baselinePath);
sourceContext = stripDerivedContext(loaded.context);
faceScale = readFaceScale(continuityDiagnostics.frequency, options.faceBox);

baselineBeautyMasks = continuityDiagnostics.baselineBeautyMasks;
baselineTextureDiagnostics = continuityDiagnostics.baselineTextureDiagnostics;
baselineLashProtection = readDiagnosticArray( ...
    continuityDiagnostics.baselineLashProtection, imageSize, ...
    'baselineLashProtection');
validateTextureDiagnostics(baselineTextureDiagnostics, imageSize);

% 重新读取当前 detector 已有的内部 evidence。该函数只消费原图、固定
% Context 的 regions/regionConfidence 和 faceScale，不接收人工真值。
evidence = reconstructExistingLashEvidence(inputImage, sourceContext, ...
    faceScale);
validateEvidenceReconstruction(evidence, baselineTextureDiagnostics, ...
    baselineLashProtection, imageSize, options.formulaTolerance);
evidence.reconstructionMaxError = max(abs( ...
    evidence.existingLashProtection(:) - baselineLashProtection(:)));

% 唯一 08.6 几何候选：现有 detector seed 在已有 dark/edge/line evidence
% 中的连通重构；soft 值复用 detector 当前 featherSoftMask(radius, .99)。
candidateGeometrySeed = evidence.connectedEvidence;
candidateLashProtection = featherSoftMask(candidateGeometrySeed, ...
    evidence.softRadius, evidence.softPeak);
candidateLashProtection(~evidence.eyeNeighborhood) = 0;
candidateLashProtection = min(max(double(candidateLashProtection), 0), 1);
validateMask(candidateLashProtection, imageSize, ...
    'candidateLashProtection');

periocularProtection = readDiagnosticArray( ...
    baselineTextureDiagnostics.periocularProtection, imageSize, ...
    'periocularProtection');
doubleEyelidProtection = readDiagnosticArray( ...
    baselineTextureDiagnostics.doubleEyelidProtection, imageSize, ...
    'doubleEyelidProtection');
reconstructedBaselineEyeDetail = max(cat(3, periocularProtection, ...
    baselineLashProtection, doubleEyelidProtection), [], 3);
baselineEyeDetail = readDiagnosticArray( ...
    baselineTextureDiagnostics.eyeDetailProtection, imageSize, ...
    'baselineEyeDetailProtection');
if max(abs(reconstructedBaselineEyeDetail(:) - baselineEyeDetail(:))) > ...
        options.formulaTolerance
    error('diagnoseLashSupportGeometryCandidate:EyeDetailAggregationMismatch', ...
        'Baseline eyeDetailProtection 聚合不一致。');
end

candidateEyeDetailProtection = max(cat(3, periocularProtection, ...
    candidateLashProtection, doubleEyelidProtection), [], 3);
% 08.6 是 geometry replacement，不把旧 lashProtection 再次 max 回去；
% 其它 texture components 仍逐项冻结。
fixedTextureComponents = max(cat(3, ...
    readDiagnosticArray(baselineTextureDiagnostics.occluderProtection, ...
    imageSize, 'occluderProtection'), ...
    readDiagnosticArray(baselineTextureDiagnostics.browProtection, ...
    imageSize, 'browProtection'), ...
    readDiagnosticArray(baselineTextureDiagnostics.lipProtection, ...
    imageSize, 'lipProtection'), ...
    readDiagnosticArray(baselineTextureDiagnostics.noseProtection, ...
    imageSize, 'noseProtection')), [], 3);
candidateTextureProtectionMask = min(max(max(fixedTextureComponents, ...
    candidateEyeDetailProtection), 0), 1);
validateMask(candidateTextureProtectionMask, imageSize, ...
    'candidateTextureProtectionMask');

candidateBeautyMasks = baselineBeautyMasks;
candidateBeautyMasks.textureProtectionMask = candidateTextureProtectionMask;
candidateBeautyMasks.protectionMask = max(cat(3, ...
    candidateTextureProtectionMask, ...
    double(baselineBeautyMasks.structureProtectionMask), ...
    double(baselineBeautyMasks.hardProtectionMask)), [], 3);
validateCandidateMaskIsolation(baselineBeautyMasks, candidateBeautyMasks, ...
    candidateTextureProtectionMask, candidateEyeDetailProtection, ...
    imageSize, options.formulaTolerance);

frequency = continuityDiagnostics.frequency;
blemishMap = continuityDiagnostics.blemishMap;
params = struct('smoothingStrength', options.smoothingStrength, ...
    'whiteningStrength', options.whiteningStrength);

% 只重跑当前既有 Smoothing / Repair / compose。frequency、blemishMap、
% Base、tone、whitening 和其它 Mask 不从 08.6 候选重新推导。
[candidateSmoothedFrequency, candidateSmoothingDiagnostics] = ...
    beauty.smoothSkinTexture(frequency, candidateBeautyMasks, ...
    params.smoothingStrength, blemishMap);
[candidateRepairedFrequency, candidateRepairDiagnostics] = ...
    beauty.repairSkinBlemishes(candidateSmoothedFrequency, ...
    candidateBeautyMasks, blemishMap, params.smoothingStrength);
processing = buildFrozenProcessing( ...
    continuityDiagnostics.baselineComposeDiagnostics);

[baselineComposed, baselineComposeDiagnostics] = ...
    beauty.composeBeautyResult(inputImage, frequency, ...
    continuityDiagnostics.repairedFrequency, baselineBeautyMasks, ...
    params.whiteningStrength, processing);
[candidate084Composed, candidate084ComposeDiagnostics] = ...
    beauty.composeBeautyResult(inputImage, frequency, ...
    continuityDiagnostics.candidateRepairedFrequency, ...
    continuityDiagnostics.candidateBeautyMasks, params.whiteningStrength, ...
    processing);
[candidate086Output, candidate086ComposeDiagnostics] = ...
    beauty.composeBeautyResult(inputImage, frequency, ...
    candidateRepairedFrequency, candidateBeautyMasks, ...
    params.whiteningStrength, processing);

baselineOutput = continuityDiagnostics.baselineComposed;
candidate084Output = continuityDiagnostics.candidateOutput;
baselineComposeMaxRgbDifference = max(abs(double(baselineComposed(:)) - ...
    double(baselineOutput(:))));
candidate084ComposeMaxRgbDifference = max(abs( ...
    double(candidate084Composed(:)) - double(candidate084Output(:))));
if baselineComposeMaxRgbDifference > options.reconstructionTolerance || ...
        candidate084ComposeMaxRgbDifference > options.reconstructionTolerance
    error('diagnoseLashSupportGeometryCandidate:FrozenComposeMismatch', ...
        'Baseline/08.4 冻结 compose 重建不一致：%.17g / %.17g。', ...
        baselineComposeMaxRgbDifference, candidate084ComposeMaxRgbDifference);
end

baselineSmoothedFrequency = continuityDiagnostics.smoothedFrequency;
candidate084SmoothedFrequency = continuityDiagnostics.candidateSmoothedFrequency;
baselineRepairedFrequency = continuityDiagnostics.repairedFrequency;
candidate084RepairedFrequency = continuityDiagnostics.candidateRepairedFrequency;
baselineRepairFineDelta = double(baselineRepairedFrequency.fine) - ...
    double(baselineSmoothedFrequency.fine);
candidate084RepairFineDelta = double(candidate084RepairedFrequency.fine) - ...
    double(candidate084SmoothedFrequency.fine);
candidate086RepairFineDelta = double(candidateRepairedFrequency.fine) - ...
    double(candidateSmoothedFrequency.fine);
baselineRepairMidDelta = double(baselineRepairedFrequency.mid) - ...
    double(baselineSmoothedFrequency.mid);
candidate084RepairMidDelta = double(candidate084RepairedFrequency.mid) - ...
    double(candidate084SmoothedFrequency.mid);
candidate086RepairMidDelta = double(candidateRepairedFrequency.mid) - ...
    double(candidateSmoothedFrequency.mid);

originalLuminance = rgb2ycbcr(im2double(inputImage));
originalLuminance = originalLuminance(:, :, 1);
validateArray(originalLuminance, imageSize, 'originalLuminance');

baselineRgbDistance = max(abs(double(baselineOutput) - ...
    double(inputImage)), [], 3);
candidate084RgbDistance = max(abs(double(candidate084Output) - ...
    double(inputImage)), [], 3);
candidate086RgbDistance = max(abs(double(candidate086Output) - ...
    double(inputImage)), [], 3);
baselineLuminanceDistance = abs(double( ...
    baselineComposeDiagnostics.outputLuminance) - double(originalLuminance));
candidate084LuminanceDistance = abs(double( ...
    candidate084ComposeDiagnostics.outputLuminance) - double(originalLuminance));
candidate086LuminanceDistance = abs(double( ...
    candidate086ComposeDiagnostics.outputLuminance) - double(originalLuminance));

baselineSupport = baselineLashProtection > 0;
candidate084LashProtection = readDiagnosticArray( ...
    continuityDiagnostics.candidateLashProtection, imageSize, ...
    'candidate084LashProtection');
candidate084Support = candidate084LashProtection > 0;
candidate086Support = candidateLashProtection > 0;
metrics = makeMetrics(manualLashMask, baselineSupport, ...
    candidate084Support, candidate086Support, baselineLashProtection, ...
    candidate084LashProtection, candidateLashProtection, ...
    baselineRepairFineDelta, candidate084RepairFineDelta, ...
    candidate086RepairFineDelta, baselineRepairMidDelta, ...
    candidate084RepairMidDelta, candidate086RepairMidDelta, ...
    baselineRgbDistance, candidate084RgbDistance, candidate086RgbDistance, ...
    baselineLuminanceDistance, candidate084LuminanceDistance, ...
    candidate086LuminanceDistance, options.nonzeroTolerance);
metrics.numericGeometryAssessment = assessNumericGeometry(metrics, ...
    options.formulaTolerance);
metrics.repairAssessment = assessRepair(metrics, options.formulaTolerance);

paths = writeArtifacts(outputFolder, inputImage, manualLashMask, ...
    baselineSupport, candidate084Support, candidate086Support, ...
    baselineRepairFineDelta, candidate084RepairFineDelta, ...
    candidate086RepairFineDelta, baselineRepairMidDelta, ...
    candidate084RepairMidDelta, candidate086RepairMidDelta, ...
    baselineOutput, candidate084Output, candidate086Output, options.lashRoi);
paths.csv = fullfile(outputFolder, 'lash_support_geometry_metrics.csv');
writeMetricsCsv(paths.csv, metrics, metrics.numericGeometryAssessment, ...
    metrics.repairAssessment, options);
paths.data = fullfile(outputFolder, 'lash_support_geometry_diagnostic.mat');

hardProtectionMaskChangedPixels = nnz( ...
    double(candidateBeautyMasks.hardProtectionMask) ~= ...
    double(baselineBeautyMasks.hardProtectionMask));
hardCoreChangedPixels = nnz( ...
    logical(baselineTextureDiagnostics.lashCore) ~= ...
    logical(baselineTextureDiagnostics.lashCore));

summary = struct( ...
    'completed', true, ...
    'issue', '08.6', ...
    'case', 'requiresVisualReview', ...
    'caseAssessment', metrics.numericGeometryAssessment, ...
    'repairAssessment', metrics.repairAssessment, ...
    'contract', continuitySummary.contract, ...
    'imagePath', imagePath, ...
    'inputSize', size(inputImage), ...
    'faceBox', double(options.faceBox), ...
    'browEye', double(options.browEyeRoi), ...
    'lashRoi', double(options.lashRoi), ...
    'parameters', params, ...
    'baselinePath', options.baselinePath, ...
    'manualLashMaskId', annotation.annotationId, ...
    'manualLashMaskIndependent', annotation.diagnosticsIndependent, ...
    'manualLashMaskFixed', annotation.fixedAfterAnnotation, ...
    'manualLashMaskPixels', nnz(manualLashMask), ...
    'runtimeCacheReused', continuitySummary.runtimeCacheReused, ...
    'sameMaskRun', true, ...
    'baseToneWhiteningFrozen', true, ...
    'onlyLashSupportGeometryChanged', true, ...
    'manualTruthUsedForGeneration', false, ...
    'candidateSeedSource', 'current detector candidate seed', ...
    'candidateEvidenceSource', ...
        'current dark/edge/line evidence intersected with eyeNeighborhood', ...
    'candidateConnection', ...
        '8-connected reconstruction through existing evidence', ...
    'candidateSoftWeightSource', ...
        'current featherSoftMask with existing faceScale softRadius and peak', ...
    'faceScale', faceScale, ...
    'softRadius', evidence.softRadius, ...
    'softPeak', evidence.softPeak, ...
    'evidenceReconstructionMaxError', evidence.reconstructionMaxError, ...
    'baselineComposeMaxRgbDifference', baselineComposeMaxRgbDifference, ...
    'candidate084ComposeMaxRgbDifference', ...
        candidate084ComposeMaxRgbDifference, ...
    'hardProtectionMaskChangedPixels', hardProtectionMaskChangedPixels, ...
    'hardCoreChangedPixels', hardCoreChangedPixels, ...
    'metrics', metrics, ...
    'paths', paths);

diagnosticData = struct( ...
    'summary', summary, ...
    'inputImage', inputImage, ...
    'annotation', annotation, ...
    'manualLashMask', manualLashMask, ...
    'frequency', frequency, ...
    'blemishMap', blemishMap, ...
    'baselineBeautyMasks', baselineBeautyMasks, ...
    'candidate084BeautyMasks', continuityDiagnostics.candidateBeautyMasks, ...
    'candidate086BeautyMasks', candidateBeautyMasks, ...
    'baselineTextureDiagnostics', baselineTextureDiagnostics, ...
    'candidate084TextureDiagnostics', ...
        continuityDiagnostics.candidateTextureDiagnostics, ...
    'candidate086TextureDiagnostics', makeCandidateTextureDiagnostics( ...
        baselineTextureDiagnostics, candidateEyeDetailProtection, ...
        candidateLashProtection), ...
    'evidence', evidence, ...
    'baselineLashProtection', baselineLashProtection, ...
    'candidate084LashProtection', candidate084LashProtection, ...
    'candidate086LashProtection', candidateLashProtection, ...
    'baselineSupport', baselineSupport, ...
    'candidate084Support', candidate084Support, ...
    'candidate086Support', candidate086Support, ...
    'candidateGeometrySeed', candidateGeometrySeed, ...
    'candidateAllowedEvidence', evidence.allowedEvidence, ...
    'candidateSoftProtection', candidateLashProtection, ...
    'smoothedFrequency', baselineSmoothedFrequency, ...
    'candidate084SmoothedFrequency', candidate084SmoothedFrequency, ...
    'candidate086SmoothedFrequency', candidateSmoothedFrequency, ...
    'repairedFrequency', baselineRepairedFrequency, ...
    'candidate084RepairedFrequency', candidate084RepairedFrequency, ...
    'candidate086RepairedFrequency', candidateRepairedFrequency, ...
    'candidate086SmoothingDiagnostics', candidateSmoothingDiagnostics, ...
    'candidate086RepairDiagnostics', candidateRepairDiagnostics, ...
    'baselineRepairFineDelta', baselineRepairFineDelta, ...
    'candidate084RepairFineDelta', candidate084RepairFineDelta, ...
    'candidate086RepairFineDelta', candidate086RepairFineDelta, ...
    'baselineRepairMidDelta', baselineRepairMidDelta, ...
    'candidate084RepairMidDelta', candidate084RepairMidDelta, ...
    'candidate086RepairMidDelta', candidate086RepairMidDelta, ...
    'baselineOutput', baselineOutput, ...
    'candidate084Output', candidate084Output, ...
    'candidate086Output', candidate086Output, ...
    'baselineComposeDiagnostics', baselineComposeDiagnostics, ...
    'candidate084ComposeDiagnostics', candidate084ComposeDiagnostics, ...
    'candidate086ComposeDiagnostics', candidate086ComposeDiagnostics, ...
    'candidate086FinalRgbDistance', candidate086RgbDistance, ...
    'candidate086FinalLuminanceDistance', candidate086LuminanceDistance, ...
    'metrics', metrics);
save(paths.data, 'diagnosticData', '-v7.3');
summary.paths = paths;
diagnosticData.summary = summary;
diagnostics = diagnosticData;

fprintf('Issue 08.6 睫毛 Support Geometry 产物：%s\n', outputFolder);
fprintf('Baseline / 08.4 / 08.6 support：%d / %d / %d\n', ...
    metrics.baseline.supportPixels, metrics.candidate084.supportPixels, ...
    metrics.candidate086.supportPixels);
fprintf('Recall：%.17g / %.17g / %.17g；Precision：%.17g / %.17g / %.17g\n', ...
    metrics.baseline.recall, metrics.candidate084.recall, ...
    metrics.candidate086.recall, metrics.baseline.precision, ...
    metrics.candidate084.precision, metrics.candidate086.precision);
fprintf('Repair Fine 绝对作用量：%.17g -> %.17g -> %.17g\n', ...
    metrics.baselineRepairFineAbsAction.sum, ...
    metrics.candidate084RepairFineAbsAction.sum, ...
    metrics.candidate086RepairFineAbsAction.sum);
fprintf('Repair Mid 绝对作用量：%.17g -> %.17g -> %.17g\n', ...
    metrics.baselineRepairMidAbsAction.sum, ...
    metrics.candidate084RepairMidAbsAction.sum, ...
    metrics.candidate086RepairMidAbsAction.sum);
fprintf('数值几何证据：%s；最终 Case 需要人工核对主图。\n', ...
    metrics.numericGeometryAssessment.case);
end

function options = normalizeOptions(options, projectRoot)
if nargin < 1 || isempty(options)
    options = struct();
end
if ~isstruct(options) || ~isscalar(options)
    error('diagnoseLashSupportGeometryCandidate:InvalidOptions', ...
        'options 必须是标量结构。');
end
fixedFields = { ...
    'faceBox', [95, 79, 286, 372]; ...
    'browEyeRoi', [165, 205, 150, 100]; ...
    'lashRoi', [102, 248, 177, 48]};
for index = 1:size(fixedFields, 1)
    name = fixedFields{index, 1};
    defaultValue = fixedFields{index, 2};
    if ~isfield(options, name) || isempty(options.(name))
        options.(name) = defaultValue;
    end
    if ~isequal(double(options.(name)), double(defaultValue))
        error('diagnoseLashSupportGeometryCandidate:NonFixedFixture', ...
            '%s 必须复用 Issue 08.6 固定值。', name);
    end
end
options.faceBox = double(options.faceBox);
options.browEyeRoi = double(options.browEyeRoi);
options.lashRoi = double(options.lashRoi);
if ~isfield(options, 'smoothingStrength') || isempty(options.smoothingStrength)
    options.smoothingStrength = 100;
end
if ~isfield(options, 'whiteningStrength') || isempty(options.whiteningStrength)
    options.whiteningStrength = 15;
end
if ~isValidStrength(options.smoothingStrength) || ...
        ~isValidStrength(options.whiteningStrength)
    error('diagnoseLashSupportGeometryCandidate:InvalidStrength', ...
        '强度必须是 0 到 100 的有限数值标量。');
end
if ~isfield(options, 'productionRoot') || isempty(options.productionRoot)
    options.productionRoot = projectRoot;
end
options.productionRoot = normalizeText(options.productionRoot, ...
    'productionRoot');
if ~isfield(options, 'baselinePath') || isempty(options.baselinePath)
    options.baselinePath = ...
        'C:\Users\JJiio\AppData\Local\Temp\image_beauty_issue02_probe\77_v32_probe.mat';
end
options.baselinePath = normalizeText(options.baselinePath, 'baselinePath');
if ~isfield(options, 'formulaTolerance') || isempty(options.formulaTolerance)
    options.formulaTolerance = 1e-12;
end
if ~isfield(options, 'reconstructionTolerance') || ...
        isempty(options.reconstructionTolerance)
    options.reconstructionTolerance = 1e-12;
end
if ~isfield(options, 'nonzeroTolerance') || isempty(options.nonzeroTolerance)
    options.nonzeroTolerance = 1e-12;
end
if ~isscalar(options.formulaTolerance) || ...
        ~isfinite(options.formulaTolerance) || options.formulaTolerance <= 0 || ...
        ~isscalar(options.reconstructionTolerance) || ...
        ~isfinite(options.reconstructionTolerance) || ...
        options.reconstructionTolerance <= 0 || ...
        ~isscalar(options.nonzeroTolerance) || ...
        ~isfinite(options.nonzeroTolerance) || options.nonzeroTolerance <= 0
    error('diagnoseLashSupportGeometryCandidate:InvalidTolerance', ...
        '公式、重建和非零容差必须是正的有限标量。');
end
options.formulaTolerance = double(options.formulaTolerance);
options.reconstructionTolerance = double(options.reconstructionTolerance);
options.nonzeroTolerance = double(options.nonzeroTolerance);
end

function root = resolveProductionRoot(root)
if ~isfolder(root) || ~isfolder(fullfile(root, 'src'))
    error('diagnoseLashSupportGeometryCandidate:InvalidProductionRoot', ...
        '生产算法根目录或 src 目录不存在：%s。', root);
end
end

function validateFixed77Fixture(inputImage, options)
if ~isequal(size(inputImage), [450, 512, 3]) || ...
        ~isequal(options.faceBox, [95, 79, 286, 372]) || ...
        ~isequal(options.browEyeRoi, [165, 205, 150, 100]) || ...
        ~isequal(options.lashRoi, [102, 248, 177, 48])
    error('diagnoseLashSupportGeometryCandidate:UnexpectedFixture', ...
        'Issue 08.6 必须使用 77.png 的 450x512x3 和固定坐标。');
end
end

function validateContinuityStage(continuitySummary, diagnostics, imageSize)
if ~isstruct(continuitySummary) || ~continuitySummary.completed || ...
        ~strcmp(continuitySummary.issue, '08.4') || ...
        continuitySummary.runtimeCacheReused || ...
        ~isstruct(diagnostics) || ~isequal(size(diagnostics.inputImage), ...
        [imageSize, 3])
    error('diagnoseLashSupportGeometryCandidate:InvalidContinuityStage', ...
        'Issue 08.4 阶段未按无缓存固定链完成。');
end
end

function image = readInputImage(imagePath)
if ~isfile(imagePath)
    error('diagnoseLashSupportGeometryCandidate:MissingImage', ...
        '输入图像不存在：%s。', imagePath);
end
image = imread(imagePath);
if ~isa(image, 'uint8') || ~isreal(image) || ndims(image) ~= 3 || ...
        size(image, 3) ~= 3
    error('diagnoseLashSupportGeometryCandidate:InvalidImage', ...
        '输入图像必须是 uint8 三通道 RGB 图像。');
end
end

function loaded = loadBaselineContext(path)
if ~isfile(path)
    error('diagnoseLashSupportGeometryCandidate:MissingBaseline', ...
        '固定 77 Context 基线不存在：%s。', path);
end
loaded = load(path, 'context');
if ~isfield(loaded, 'context') || ~isstruct(loaded.context) || ...
        ~isscalar(loaded.context)
    error('diagnoseLashSupportGeometryCandidate:InvalidBaseline', ...
        '固定 77 基线缺少有效 context：%s。', path);
end
end

function context = stripDerivedContext(context)
names = {'runtimeCache', 'textureProtectionMask', ...
    'structureProtectionMask', 'whiteningProtectionMask', ...
    'chromaProtectionMask', 'toneProtectionMask', 'strengthMap', ...
    'faceStrengthMap', 'nonFaceStrengthMap', 'protectionMasks'};
present = names(isfield(context, names));
if ~isempty(present)
    context = rmfield(context, present);
end
end

function faceScale = readFaceScale(frequency, faceBox)
if isfield(frequency, 'faceScale') && isnumeric(frequency.faceScale) && ...
        isscalar(frequency.faceScale) && isfinite(frequency.faceScale) && ...
        frequency.faceScale > 0
    faceScale = double(frequency.faceScale);
else
    faceScale = min(double(faceBox(3:4)));
end
end

function evidence = reconstructExistingLashEvidence(inputImage, context, ...
        faceScale)
imageSize = [size(inputImage, 1), size(inputImage, 2)];
if ~isfield(context, 'regions') || ~isfield(context, 'regionConfidence')
    error('diagnoseLashSupportGeometryCandidate:MissingSemanticEvidence', ...
        '固定 Context 缺少当前 detector 所需的 regions/regionConfidence。');
end
regions = context.regions;
confidence = context.regionConfidence;
required = {'leftEye', 'rightEye', 'leftBrow', 'rightBrow'};
if ~all(isfield(regions, required)) || ~all(isfield(confidence, required))
    error('diagnoseLashSupportGeometryCandidate:MissingSemanticEvidence', ...
        '固定 Context 缺少眼睛或眉毛既有语义 evidence。');
end
leftEyeEvidence = min(double(regions.leftEye), ...
    double(confidence.leftEye));
rightEyeEvidence = min(double(regions.rightEye), ...
    double(confidence.rightEye));
browEvidence = max(min(double(regions.leftBrow), ...
    double(confidence.leftBrow)), min(double(regions.rightBrow), ...
    double(confidence.rightBrow)));
validateArray(leftEyeEvidence, imageSize, 'leftEyeEvidence');
validateArray(rightEyeEvidence, imageSize, 'rightEyeEvidence');
validateArray(browEvidence, imageSize, 'browEvidence');

grayImage = im2double(rgb2gray(inputImage));
identityThreshold = .45;
softSupportThreshold = .20;
identityMasks = {leftEyeEvidence >= identityThreshold, ...
    rightEyeEvidence >= identityThreshold};
softSupportMasks = {leftEyeEvidence >= softSupportThreshold & ...
    leftEyeEvidence < identityThreshold, ...
    rightEyeEvidence >= softSupportThreshold & ...
    rightEyeEvidence < identityThreshold};
browCore = browEvidence >= identityThreshold;
periocularRadius = min(24, max(9, round(.040 * double(faceScale))));
softRadius = min(5, max(2, round(.008 * double(faceScale))));

allNeighborhood = false(imageSize);
allRing = false(imageSize);
allDarkCandidate = false(imageSize);
allEdgeCandidate = false(imageSize);
allLineSupport = false(imageSize);
allDetectorCandidate = false(imageSize);
allLashCore = false(imageSize);
allLashProtection = zeros(imageSize);
allLaunchMask = false(imageSize);
allNearEye = false(imageSize);
perEye = cell(1, numel(identityMasks));
for eyeIndex = 1:numel(identityMasks)
    identityCore = identityMasks{eyeIndex};
    softSupport = softSupportMasks{eyeIndex};
    launchMask = identityCore | softSupport;
    if ~any(launchMask(:))
        continue;
    end
    currentBand = imdilate(launchMask, ...
        strel('disk', periocularRadius, 0));
    currentRing = currentBand & ~launchMask;
    if any(browCore(:))
        browRadius = min(5, max(2, round(.010 * double(faceScale))));
        browExclusion = imdilate(browCore, strel('disk', browRadius, 0));
        currentRing(browExclusion) = false;
    end
    current = reconstructExistingLashLines(grayImage, launchMask, ...
        currentRing, identityCore, faceScale, softRadius, ...
        any(softSupport(:)));
    allNeighborhood = allNeighborhood | currentBand;
    allRing = allRing | currentRing;
    allDarkCandidate = allDarkCandidate | current.darkCandidate;
    allEdgeCandidate = allEdgeCandidate | current.edgeCandidate;
    allLineSupport = allLineSupport | current.lineSupport;
    allDetectorCandidate = allDetectorCandidate | current.candidate;
    allLashCore = allLashCore | current.lashCore;
    allLashProtection = max(allLashProtection, current.protection);
    allLaunchMask = allLaunchMask | launchMask;
    allNearEye = allNearEye | current.nearEye;
    perEye{eyeIndex} = current;
end

