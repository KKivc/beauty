    source = context.(fieldName);
else
    source = struct();
end
for index = 1:numel(names)
    name = names{index};
    if isfield(source, name) && isequal(size(source.(name)), imageSize)
        values.(name) = double(source.(name));
    else
        values.(name) = zeros(imageSize);
    end
end
end

function evidence = semanticEvidence(regions, confidence, names)
